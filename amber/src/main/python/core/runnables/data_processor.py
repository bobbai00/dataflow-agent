# Pandas dtype name → AttributeType. Object columns are sampled separately to
# distinguish STRING / LIST / STRUCT.
_PANDAS_DTYPE_TO_ATTRIBUTE_TYPE: Dict[str, AttributeType] = {
    "int8": AttributeType.LONG,
    "int16": AttributeType.LONG,
    "int32": AttributeType.LONG,
    "int64": AttributeType.LONG,
    "uint8": AttributeType.LONG,
    "uint16": AttributeType.LONG,
    "uint32": AttributeType.LONG,
    "uint64": AttributeType.LONG,
    "float16": AttributeType.DOUBLE,
    "float32": AttributeType.DOUBLE,
    "float64": AttributeType.DOUBLE,
    "bool": AttributeType.BOOL,
    "datetime64[ns]": AttributeType.TIMESTAMP,
    "datetime64[us]": AttributeType.TIMESTAMP,
    "datetime64[ms]": AttributeType.TIMESTAMP,
}


def _to_dataframe(output: Any) -> Optional[pandas.DataFrame]:
    """
    Coerce a Table-API yield to a pandas DataFrame for inference + profiling.
    Returns None for tuple-yielding outputs (TupleLike), None values, or any
    other object — those flow through the existing tuple path unchanged.
    """
    if isinstance(output, pandas.DataFrame):
        return output
    if isinstance(output, pa.Table):
        return output.to_pandas()
    # Texera Table model exposes to_pandas() — duck-typed.
    if hasattr(output, "to_pandas") and callable(getattr(output, "to_pandas")):
        try:
            df = output.to_pandas()
            if isinstance(df, pandas.DataFrame):
                return df
        except Exception:
            return None
    return None


def _sanitize_float(value: Any) -> Optional[float]:
    """
    Coerce a pandas describe() result to a finite float. NaN and Inf
    become None so callers don't have to special-case them.
    """
    if value is None:
        return None
    try:
        f = float(value)
    except (TypeError, ValueError):
        return None
    if math.isnan(f) or math.isinf(f):
        return None
    return f


def _format_number(value: float) -> str:
    """
    Compact numeric formatting for the stats line: integer-valued floats
    drop the decimal point ("95.0" -> "95"), other floats use up to 4
    significant digits via `:.4g` ("219.234" -> "219.2", "0.000456" -> "0.000456").
    """
    if value == int(value):
        return str(int(value))
    return f"{value:.4g}"


def _format_datetime(value: Any) -> str:
    """
    Datetime stringification. Strips a trailing "00:00:00" so date-only
    columns render as "2023-01-15" instead of "2023-01-15 00:00:00".
    """
    s = str(value)
    if s.endswith(" 00:00:00"):
        return s[: -len(" 00:00:00")]
    return s


def _container_kind(value: Any) -> Optional[str]:
    """
    Classify a non-null cell as ``"list"`` (list / tuple / set / ndarray)
    or ``"struct"`` (dict), or ``None`` if it isn't a container. Used by
    `_compute_column_stats` to type LIST and STRUCT columns separately
    from the generic str fallback. ndarrays are routed to ``"list"``
    because that's how the engine's AttributeType.LIST marshaller
    transports them (see `coerce_value_to_type`).
    """
    if isinstance(value, dict):
        return "struct"
    if isinstance(value, (list, tuple, set)):
        return "list"
    if hasattr(value, "tolist") and not isinstance(value, (str, bytes, bool, int, float)):
        return "list"
    return None


def _is_container_column(non_null: pandas.Series) -> bool:
    """
    True iff a sample of the column's non-null cells are containers
    (list / dict / tuple / set / ndarray). Sampled rather than scanned
    because the cell-by-cell check on long columns is expensive — the
    first few non-null values are enough to discriminate, since real
    UDFs don't mix scalar and container cells in the same column.
    """
    sample = non_null.head(10)
    if sample.empty:
        return False
    container_count = sum(1 for v in sample if _container_kind(v) is not None)
    return container_count == len(sample)


def _safe_len(value: Any) -> Optional[int]:
    """
    ``len(value)`` on a container, else ``None``. Used by the list/struct
    branch of `_compute_column_stats` to compute items-per-cell shape
    summaries. Falls through silently on cells with no ``__len__``.
    """
    try:
        return len(value)
    except Exception:
        return None


def _is_bytes_column(non_null: pandas.Series) -> bool:
    """
    True iff every sampled non-null cell is a ``bytes`` / ``bytearray``
    payload. Used by the `(binary)` branch of `_compute_column_stats`
    when a UDF returned raw bytes directly. Sampled rather than scanned
    for symmetry with `_is_container_column` — real UDFs don't mix
    scalar and bytes cells in the same column.
    """
    sample = non_null.head(10)
    if sample.empty:
        return False
    return all(isinstance(v, (bytes, bytearray)) for v in sample)


# Cell classes the stats branches above already handle: don't route them
# into the (binary) class-name branch.
_STATS_PRIMITIVE_TYPES = (
    str,
    int,
    float,
    bool,
    type(None),
    bytes,
    bytearray,
    list,
    tuple,
    set,
    dict,
)


def _is_binary_class_column(non_null: pandas.Series) -> bool:
    """
    True iff every sampled non-null cell is an instance of a single
    "non-primitive" Python class — i.e. an object that the
    BINARY-pickle path would handle at cast_to_schema time. Used by
    `(binary)` to surface the Python class name (shapely Polygon,
    pandas Timestamp on object columns, etc.) BEFORE the cells are
    actually converted to bytes. Without this we'd hit the generic
    str fallback and emit a misleading `(str): distinct=N` line.

    Pandas-known classes (``pandas.Timestamp``, ``numpy`` scalars) are
    excluded because their stats already render correctly via the
    numeric / datetime branches when the column has the appropriate
    dtype. We only fire when the cells are genuinely third-party /
    user-defined classes the pickled-object path would carry.
    """
    sample = non_null.head(10)
    if sample.empty:
        return False
    first_type = type(sample.iloc[0])
    if first_type in _STATS_PRIMITIVE_TYPES:
        return False
    # ndarrays are routed by _is_container_column; numpy scalars and
    # pandas types render via the dtype-based branches.
    mod = getattr(first_type, "__module__", "") or ""
    if mod.startswith("numpy") or mod.startswith("pandas"):
        return False
    return all(type(v) is first_type for v in sample)


def _embedded_class_name(value: Any) -> Optional[str]:
    """
    Cheap peek into a bytes payload for the embedded class name written
    by `_encode_pickled_object` (see tuple.py). Returns ``None`` for
    legacy ``pickle    `` payloads (no embedded name) and for raw-bytes
    cells. Imported lazily to avoid a hard cycle between
    `data_processor` and `models.tuple`.
    """
    try:
        from core.models.tuple import pickled_object_class_name
    except Exception:
        return None
    return pickled_object_class_name(value)


class DataProcessor(Runnable, Stoppable):
    def __init__(self, context: Context):
        self._running = Event()
        self._context = context
        # Set to True after the first DataFrame yield triggers schema
        # inference + (optional) port rewrite. Subsequent yields skip the
        # inference work and reuse whatever port schema is now active.
        self._schema_inferred: bool = False
        self._table_profile = None

    def run(self) -> None:
        """
        Start the data processing loop. Wait for context switch conditions to be met,
        then continuously process markers or tuples until stopped.
        """
        with self._context.tuple_processing_manager.context_switch_condition:
            self._context.tuple_processing_manager.context_switch_condition.wait()
        self._running.set()
        self._check_and_process_debug_command()
        while self._running.is_set():
            tpm = self._context.tuple_processing_manager
            spm = self._context.state_processing_manager
            has_marker = tpm.current_internal_marker is not None
            has_state = spm.current_input_state is not None
            has_tuple = tpm.current_input_tuple is not None
            # MainLoop is single-threaded and sets at most one of
            # current_internal_marker / current_input_state /
            # current_input_tuple per cycle before switching to here, so
            # exactly one slot must be populated on every iteration.
            if has_marker + has_state + has_tuple != 1:
                raise RuntimeError(
                    "DataProcessor expected exactly one queued input per "
                    f"iteration, got marker={has_marker}, state={has_state}, "
                    f"tuple={has_tuple}"
                )
            if has_marker:
                self.process_internal_marker(tpm.get_internal_marker())
            elif has_state:
                self.process_state(spm.get_input_state())
            else:
                self.process_tuple()

    def process_internal_marker(self, internal_marker: InternalMarker) -> None:
        with self._executor_session() as (executor, port_id):
            if isinstance(internal_marker, StartChannel):
                self._set_output_state(executor.produce_state_on_start(port_id))
            elif isinstance(internal_marker, EndChannel):
                # Empty streams still carry a port schema. Tuples cannot
                # convey it when no rows arrive, so pass the latest runtime
                # schema before table/state callbacks materialize the buffer.
                input_port = self._context.tuple_processing_manager.current_input_port_id
                if isinstance(executor, TableOperator) and input_port is not None:
                    executor._set_input_schema(port_id, self._context.input_manager.get_port(input_port).get_schema())
                self._set_output_state(executor.produce_state_on_finish(port_id))
                # Flush the state to MainLoop before producing tuples so the
                # state and the tuple stream don't share a single switch.
                self._switch_context()
                self._set_output_tuple(executor.on_finish(port_id))

    def process_state(self, state: State) -> None:
        """
        Process an input marker by invoking appropriate state
        or tuple generation based on the marker type.
        """
        with self._executor_session() as (executor, port_id):
            self._set_output_state(executor.process_state(state, port_id))

    def process_tuple(self) -> None:
        """
        Process an input tuple by invoking the executor's tuple processing method.
        """
        finished_current = self._context.tuple_processing_manager.finished_current
        while not finished_current.is_set():
            with self._executor_session() as (executor, port_id):
                tuple_ = self._context.tuple_processing_manager.get_input_tuple()
                self._set_output_tuple(executor.process_tuple(tuple_, port_id))

    @contextmanager
    def _executor_session(self):
        """
        Open one executor invocation: hand back (executor, port_id) under a
        print-capture session, route any exception to the exception manager
        and queue the stack trace as a console message, and always switch
        back to MainLoop on exit. Reporting must happen *before* the
        switch: MainLoop's post-switch hook flushes console messages and
        then enters EXCEPTION_PAUSE, so anything queued after the switch
        would arrive at the coordinator only after the worker resumes.
        """
        joined = False
        coerced = False
        try:
            executor = self._context.executor_manager.executor
            port_id = self._context.tuple_processing_manager.get_input_port_id()
            # Lever 4: instrument to_numeric/to_datetime coerce for every
            # operator — coercion dataloss can happen in any UDF (load or
            # process). Guarded; can never break the user's conversion.
            coerced = self._install_coercion_telemetry()
            # A7: record which files this operator actually read (multi-file
            # loads only). Guarded; never alters the read result.
            try:
                from core.util import file_io_telemetry
                file_io_telemetry.install()
            except Exception:
                pass
            with replace_print(
                self._context.worker_id,
                self._context.console_message_manager.print_buf,
            ):
                yield executor, port_id
        except Exception as err:
            logger.exception(err)
            exc_info = sys.exc_info()
            self._context.exception_manager.set_exception_info(exc_info)
            # UDF data-path errors use the user-code-locating reporter
            # (_report_exception): exception type+message, the UDF's failing
            # line, and the operator source — with the engine's internal
            # multi-frame traceback intentionally omitted. #5783 had
            # centralized this onto create_error_console_message, which dumped
            # the raw engine traceback (data_processor/tuple frames + embedded
            # data) that the agent cannot act on. Restored here so the agent
            # sees its own code + line, not engine internals.
            self._report_exception(exc_info)
        finally:
            if coerced:
                try:
                    from core.util import coercion_telemetry
                    coercion_telemetry.uninstall()
                except Exception:
                    pass
            try:
                from core.util import file_io_telemetry
                file_io_telemetry.uninstall()
            except Exception:
                pass
            self._switch_context()

    @staticmethod
    def _install_coercion_telemetry() -> bool:
        """Install the transparent to_numeric/to_datetime coerce instrumentation
        (lever 4) for every operator — coercion dataloss is common and can occur
        in any UDF. Guarded; returns True iff installed."""
        try:
            from core.util import coercion_telemetry
        except Exception:
            return False
        coercion_telemetry.install()
        return True

    def _set_output_tuple(self, output_iterator: Iterator[Optional[TupleLike]]) -> None:
        """
        Set the output tuple after processing by the executor.
        """
        for output in output_iterator:
            # output could be a None, a TupleLike, or a TableLike.
            self._maybe_apply_runtime_schema(output)
            whole = self._arrow_output(output)
            if whole is not None:
                # The rows now live in `whole`: let the frame go before they
                # are sent and written (2.9 GB for an 8.6 M-row scan).
                output = None
                self._switch_context()
                self._context.tuple_processing_manager.current_output_tuple = whole
                self._switch_context()
                continue
            for output_tuple in all_output_to_tuple(output):
                if output_tuple is not None:
                    output_tuple.finalize(
                        self._context.output_manager.get_port().get_schema()
                    )
                self._switch_context()
                self._context.tuple_processing_manager.current_output_tuple = (
                    output_tuple
                )
                self._switch_context()
        self._context.tuple_processing_manager.finished_current.set()

    def _arrow_output(self, output: Any) -> Optional[ArrowOutput]:
        """A yielded DataFrame as one Arrow table, when its rows may leave
        whole (``OutputManager.accepts_arrow``) and every column already
        holds the port's type (``frame_to_arrow``): no Tuple, cast, type
        check and size walk per row. None keeps the per-row path, which also
        reports any row that does not fit the schema. Loop operators keep it."""
        if not isinstance(output, pandas.DataFrame) or len(output) == 0:
            return None
        if isinstance(self._context.executor_manager.executor, (LoopStartOperator, LoopEndOperator)):
            return None
        output_manager = self._context.output_manager
        if not output_manager.accepts_arrow():
            return None
        try:
            table = frame_to_arrow(output, output_manager.get_port().get_schema())
        except Exception:
            return None
        return ArrowOutput(table) if table is not None else None

    # ------------------------------------------------------------------
    # Runtime schema inference + per-column profiling (Table API only)
    # ------------------------------------------------------------------

    def _maybe_apply_runtime_schema(self, output: Any) -> None:
        """
        Table-API path. On the first yielded DataFrame, infer the schema from
        the DataFrame's dtypes and reconcile against the declared port schema:
          - declared empty → silently rewrite port + recreate writers
          - declared non-empty + mismatch → raise (UDF contract violation)
          - declared non-empty + match → no-op
        Subsequent yields skip inference and reuse the now-active port
        schema; per-column stats are still recomputed on every yield so the
        agent renderer sees the most recent table. No-op for non-Table
        yields (tuple-yielding UDFs must declare their schema upfront).
        """
        df = _to_dataframe(output)
        if df is None:
            return

        if not self._schema_inferred:
            self._schema_inferred = True
            inferred = self._infer_schema_from_dataframe(df)
            declared = self._context.output_manager.get_port().get_schema()
            if inferred != declared:
                if declared.get_attr_names():
                    # Static-schema operator (e.g. PythonUDFV2): the declared
                    # schema is authoritative. Before rejecting, bridge benign
                    # numeric discrepancies that Tuple.cast_to_schema fixes per
                    # cell — chiefly a nullable integer column that round-trips
                    # through pandas as float64 (pandas int64 cannot hold
                    # nulls). For those, keep the declared schema and let
                    # finalize() coerce DOUBLE→LONG (NaN→None). Only a genuine
                    # mismatch (changed columns, fractional data declared as an
                    # integer, or a non-numeric type change) still raises.
                    if not self._numeric_mismatch_is_bridgeable(
                        df, declared, inferred
                    ):
                        raise RuntimeError(
                            f"Output schema mismatch: declared {declared}, "
                            f"got {inferred}."
                        )
                    logger.info(
                        "Bridged benign numeric schema discrepancy against "
                        f"declared schema {declared} (inferred {inferred})."
                    )
                else:
                    self._context.output_manager.get_port().set_schema(inferred)
                    for port_id in self._context.output_manager.get_port_ids():
                        self._context.output_manager.recreate_port_storage_writer(
                            port_id, inferred
                        )
                    logger.info(
                        f"Schema inferred from DataFrame dtypes: {inferred}"
                    )

        self._publish_column_stats(df)

    @staticmethod
    def _numeric_mismatch_is_bridgeable(
        df: pandas.DataFrame, declared: Schema, inferred: Schema
    ) -> bool:
        """
        True when every column where `inferred` differs from `declared` is a
        benign numeric discrepancy that `Tuple.cast_to_schema` bridges per
        cell, so the declared schema can stand unchanged:

          - declared INT/LONG vs inferred DOUBLE → bridgeable only when the
            column's non-null values are all integral. This is the common
            "nullable integer column arrives in pandas as float64" case
            (pandas int64 cannot hold NaN); cast_to_schema maps NaN→None and
            integer-valued floats→int.
          - any other pair within {INT, LONG, DOUBLE} → bridgeable (lossless,
            e.g. INT→LONG, or int values declared DOUBLE).

        Anything else — a changed/missing/extra/reordered column, a
        non-numeric type change (e.g. STRING↔LONG), or genuinely fractional
        data declared as an integer — is NOT bridgeable and stays a hard
        mismatch so real UDF contract violations still surface.
        """
        numeric = (AttributeType.INT, AttributeType.LONG, AttributeType.DOUBLE)
        declared_names = declared.get_attr_names()
        if declared_names != inferred.get_attr_names():
            return False
        for name in declared_names:
            declared_type = declared.get_attr_type(name)
            inferred_type = inferred.get_attr_type(name)
            if declared_type == inferred_type:
                continue
            if declared_type not in numeric or inferred_type not in numeric:
                return False
            # Narrowing a float column to an integer type is only safe when
            # the observed values carry no fractional part.
            if (
                declared_type in (AttributeType.INT, AttributeType.LONG)
                and inferred_type == AttributeType.DOUBLE
            ):
                col = pandas.to_numeric(df[name], errors="coerce").dropna()
                if len(col) and not (col == col.round()).all():
                    return False
        return True

    def _infer_schema_from_dataframe(self, df: pandas.DataFrame) -> Schema:
        """
        Build a Texera Schema from a pandas DataFrame's dtypes. Object
        columns are handed off to `_infer_type_from_object_column`, which
        runs a whole-column `pandas.api.types.infer_dtype` scan (handles
        nulls and mixed-numeric properly); other dtypes go through
        `_map_pandas_dtype_to_attribute_type`, which understands pandas
        extension dtypes (Int64/Float64/boolean/string/categorical/
        timedelta64) and the numpy primitives.

        Column-name handling matches `Table.as_tuples`: labels are
        stringified (a `pd.read_excel(header=None)` DataFrame carries int
        RangeIndex labels) and deduplicated (two columns called "x" become
        "x" and "x.1") so the inferred Schema lines up cell-for-cell with
        the deduped Tuples produced downstream. Columns are read
        positionally via `df.iloc[:, i]` rather than `df[name]` so a
        duplicate label doesn't return a DataFrame instead of a Series
        (which would `AttributeError` on `.dtype`).
        """
        from core.models.table import deduplicate_columns

        str_columns = [str(c) for c in df.columns]
        deduped_columns, _ = deduplicate_columns(str_columns)
        schema = Schema()
        for i, col_name in enumerate(deduped_columns):
            col = df.iloc[:, i]
            if pandas.api.types.is_object_dtype(col):
                attr_type = self._infer_type_from_object_column(col)
            else:
                attr_type = self._map_pandas_dtype_to_attribute_type(col.dtype)
            schema.add(col_name, attr_type)
        return schema

    @staticmethod
    def _infer_type_from_object_column(col: pandas.Series) -> AttributeType:
        """
        Infer an AttributeType for an object-dtype column. Uses pandas'
        `infer_dtype` so a column of `[1, None, 2]` types as LONG (not
        whatever the first non-null cell happens to be) and a column of
        `[1, 1.5, None]` types as DOUBLE.

        Falls back to type-sampling when pandas reports `mixed` (or one of
        the catch-all kinds): up to 100 non-null values are inspected, and
        a column is LIST/STRUCT only when *every* sampled value is a list
        or dict respectively. Anything else (truly mixed, or unknown kind
        with no values to sample) falls back to STRING, which is the
        safest type for downstream serialization.
        """
        inferred = pandas.api.types.infer_dtype(col, skipna=True)

        if inferred == "integer":
            return AttributeType.LONG
        if inferred == "floating" or inferred == "mixed-integer-float":
            # Floats can represent ints, so a mix of the two is still DOUBLE.
            return AttributeType.DOUBLE
        if inferred == "boolean":
            return AttributeType.BOOL
        if inferred == "string":
            return AttributeType.STRING
        if inferred == "bytes":
            return AttributeType.BINARY
        if inferred in ("datetime", "datetime64", "date"):
            return AttributeType.TIMESTAMP

        non_null = col.dropna()
        if non_null.empty:
            return AttributeType.STRING

        sample = non_null.head(100)
        types_seen = set(type(v) for v in sample)
        if types_seen == {list}:
            return AttributeType.LIST
        if types_seen == {dict}:
            return AttributeType.STRUCT
        if types_seen == {bytes} or types_seen == {bytearray}:
            return AttributeType.BINARY
        return AttributeType.STRING

    @staticmethod
    def _map_pandas_dtype_to_attribute_type(dtype) -> AttributeType:
        """
        Map a numpy/pandas dtype to an AttributeType. Covers numpy primitives
        via the lookup table, then falls back to string-name matching for
        pandas extension dtypes (capitalized nullable types, StringDtype,
        CategoricalDtype, datetime64 with tz, timedelta64). Unknown dtypes
        default to BINARY, which gets pickled downstream.
        """
        dtype_str = str(dtype)
        if dtype_str in _PANDAS_DTYPE_TO_ATTRIBUTE_TYPE:
            return _PANDAS_DTYPE_TO_ATTRIBUTE_TYPE[dtype_str]
        # Pandas nullable integer types: Int8/Int16/Int32/Int64, UInt8…UInt64.
        if dtype_str.startswith("Int") or dtype_str.startswith("UInt"):
            return AttributeType.LONG
        # Pandas nullable float types: Float32, Float64.
        if dtype_str.startswith("Float"):
            return AttributeType.DOUBLE
        # Pandas nullable boolean.
        if dtype_str == "boolean":
            return AttributeType.BOOL
        # Pandas StringDtype, under any spelling ("string", "string[pyarrow]",
        # or pandas 3's default "str"). A new name must not turn text into
        # pickled bytes: the agent then sees "<builtins.str, size = 55 bytes>".
        if dtype_str == "string" or pandas.api.types.is_string_dtype(dtype):
            return AttributeType.STRING
        # Categorical — stringify the categories for downstream consumption.
        if hasattr(dtype, "categories"):
            return AttributeType.STRING
        # datetime64 with or without tz (e.g. "datetime64[ns, UTC]").
        if dtype_str.startswith("datetime64") or hasattr(dtype, "tz"):
            return AttributeType.TIMESTAMP
        # timedelta64 — store as int nanoseconds.
        if dtype_str.startswith("timedelta64"):
            return AttributeType.LONG
        logger.debug(f"Unknown pandas dtype {dtype_str!r}, defaulting to BINARY")
        return AttributeType.BINARY

    def _publish_column_stats(self, df: pandas.DataFrame) -> None:
        """
        Compute per-column statistics from the DataFrame and publish them
        via StatisticsManager.set_result_statistics so they ride out on the
        next WorkerStatistics emission.

        Each emitted value is a pre-formatted display string of the shape
        `"(type): k=v, k=v, ..."` — the agent-service renderer just wraps
        each one with `- "col" ` and emits it under a `Column stats:` block,
        so the format is fully owned here. See `_compute_column_stats` for
        the per-type field set.

        Columns are read positionally via `df.iloc[:, i]` (not `df[name]`)
        so duplicate labels — e.g. a DataFrame with two columns both named
        "x" — return a Series per column rather than a DataFrame, which is
        what `_compute_column_stats` needs. Names are deduped through the
        same `deduplicate_columns` helper as `Table.as_tuples` so the stats
        keys line up with the engine's Schema field names.
        """
        from core.models.table import deduplicate_columns

        # A native operator's table carries its own typed profile
        # (_publish_table_profile), and the agent renders only that: these
        # display strings and table hints are never read for it, and they
        # cost a full pass per column (about 110 s on an 8.6 M-row scan).
        native = isinstance(df.attrs.get("native_v2"), dict)
        str_columns = [str(c) for c in df.columns]
        deduped_columns, _ = deduplicate_columns(str_columns)
        stats: Dict[str, str] = {}
        for i, col_name in enumerate([] if native else deduped_columns):
            col = df.iloc[:, i]
            stats[col_name] = self._compute_column_stats(col)
        # Lever 4: attach any coerce-to-NaN dataloss diagnostics.
        try:
            from core.util import coercion_telemetry
            cdiags = coercion_telemetry.drain()
            if cdiags:
                stats["__coercion_telemetry__"] = " || ".join(cdiags)
        except Exception:
            pass
        # Table-structure hints (#25/#26/#27): pre-emptive grain / partition /
        # dirty-load signals, attached under a reserved key like the telemetry
        # above. Always computed (cheap, one pass); the agent-service strips this
        # key from schema/stats rendering and surfaces it only when the gated
        # `tableStructureHint` flag is on, so this is a no-op by default.
        try:
            table_hints = [] if native else self._detect_table_structure(df)
            if table_hints:
                stats["__table_hints__"] = " || ".join(table_hints)
        except Exception:
            pass
        # A7: multi-file load provenance — the file list the agent's own glob
        # matched, which the rendered result otherwise never shows. Fact only,
        # no advice (see file_io_telemetry docstring). Reserved key: the
        # agent-service strips it from schema/stats rendering and surfaces it on
        # the structural-hints rung.
        try:
            from core.util import file_io_telemetry
            fdiags = file_io_telemetry.drain()
            if fdiags:
                stats["__file_io__"] = " || ".join(fdiags)
        except Exception:
            pass
        self._context.statistics_manager.set_result_statistics(stats)
        self._publish_table_profile(df)

    def _publish_table_profile(self, df: pandas.DataFrame) -> None:
        metadata = df.attrs.get("native_v2")
        if self._table_profile is None:
            if (
                not isinstance(metadata, dict)
                or metadata.get("profileCollection") is not True
            ):
                return
            try:
                from core.util.table_profile import ProfileAccumulator

                self._table_profile = ProfileAccumulator(
                    self._context.worker_id, metadata
                )
            except Exception:
                # A partial worker deployment must not fail a valid data result.
                # Missing telemetry is reported as unavailable by the consumer.
                return
        try:
            self._table_profile.add(df)
        except Exception:
            self._table_profile.fail("profiler_error")
        self._store_table_profile()

    def _store_table_profile(self) -> None:
        if self._table_profile is not None:
            try:
                self._context.statistics_manager.set_profile_statistics(
                    self._table_profile.key, self._table_profile.encode()
                )
            except Exception:
                # Optional telemetry failure never fails the table execution.
                # The consumer treats a missing envelope as unavailable.
                pass

    def finish_table_profile(self) -> None:
        if self._table_profile is not None:
            self._table_profile.finish()
            self._store_table_profile()

    @staticmethod
    def _compute_column_stats(col: pandas.Series) -> str:
        """
        Produce a per-column stats display line of the form
        `"(<type>): null=N[, <type-specific kvs>]"`. The caller wraps it
        with `- "<colname>" ` to get the final rendered line.

        Per-type field set:
          - bool      → null, true, false
          - numeric   → null, mean, min, max, [top_10={...}]
                                                      (top_10 only when
                                                       0 < distinct <= 10 —
                                                       numeric columns with
                                                       small finite domains
                                                       look categorical even
                                                       though pandas typed
                                                       them as numbers; the
                                                       per-value frequency
                                                       map is then more
                                                       informative than just
                                                       mean/min/max)
          - datetime  → null, min, max               (ISO strings; trailing
                                                       " 00:00:00" stripped for
                                                       date-only columns)
          - str/other → null, distinct[, top_5={...}]
                                                      (top_5 only when
                                                       0 < distinct <= 5 — for
                                                       low-cardinality string
                                                       columns. High-cardinality
                                                       columns get just
                                                       null + distinct.)

        Type-conditional top-N cap: numeric/bool get 10, str gets 5. Strings
        tend to have longer raw values (multi-word categories, paths), so a
        tighter cap controls token cost; numeric values are short, so a
        wider cap is cheap and lets the agent see the full small-domain
        histogram. Bool already gets `true/false` counts which subsume the
        same information.

        Intentionally drops the older `count` / `std` / `p25` / `median` /
        `p75` fields — they were noisy and the agent rarely acted on them.

        Downstream per-cell size cap (`SyncExecutionResource.truncateColumn
        StatsValues` using the agent's `maxOperatorResultCellCharLimit`)
        applies on top of the per-type cap, so a pathological column with
        very long string keys still can't blow the context budget.
        """
        null = int(col.isna().sum())
        non_null = col.dropna()
        parts = [f"null={null}"]

        if pandas.api.types.is_bool_dtype(col):
            col_type = "bool"
            if not non_null.empty:
                parts.append(f"true={int((non_null == True).sum())}")  # noqa: E712
                parts.append(f"false={int((non_null == False).sum())}")  # noqa: E712
        elif pandas.api.types.is_numeric_dtype(col):
            col_type = "numeric"
            if not non_null.empty:
                try:
                    mean = _sanitize_float(non_null.mean())
                    cmin = _sanitize_float(non_null.min())
                    cmax = _sanitize_float(non_null.max())
                    if mean is not None:
                        parts.append(f"mean={_format_number(mean)}")
                    if cmin is not None:
                        parts.append(f"min={_format_number(cmin)}")
                    if cmax is not None:
                        parts.append(f"max={_format_number(cmax)}")
                except Exception:
                    pass
                # Append top_10 for low-cardinality numeric columns (e.g. a
                # year column with 5 distinct values, or a coded category
                # accidentally typed as int). Same distinct-count gate as
                # strings — high-cardinality numeric columns get the
                # long-tail dropped because the agent already has
                # mean/min/max for the shape.
                try:
                    distinct = int(non_null.nunique())
                    if 0 < distinct <= 10:
                        top = non_null.value_counts().head(10)
                        inner = ", ".join(
                            f"{_format_number(_sanitize_float(k) or 0)}={int(v)}"
                            if _sanitize_float(k) is not None
                            else f"{k}={int(v)}"
                            for k, v in top.items()
                        )
                        parts.append(f"top_10={{{inner}}}")
                except Exception:
                    pass
        elif pandas.api.types.is_datetime64_any_dtype(col):
            col_type = "datetime"
            if not non_null.empty:
                try:
                    parts.append(f"min={_format_datetime(non_null.min())}")
                    parts.append(f"max={_format_datetime(non_null.max())}")
                except Exception:
                    pass
        elif (
            not non_null.empty
            and _is_container_column(non_null)
        ):
            # Container-cell columns (list / tuple / set / dict / ndarray)
            # type as their own kind. Cardinality and top_N frequency
            # analysis don't make sense for these — `["red","blue"]` and
            # `["blue","red"]` shouldn't be treated as a stable categorical
            # label, and stringified containers blow the per-cell budget
            # on any non-trivial dataset.
            #
            # For LIST-shaped cells (list / tuple / set / ndarray) we
            # surface the per-cell element-count distribution
            # (items_min / items_max / items_mean) — that's the one piece
            # of shape information the agent typically needs to decide
            # whether to explode the column or aggregate it.
            #
            # For STRUCT-shaped cells (dict) we emit ONLY `null=N`. Dict
            # keys-per-cell is rarely a useful planning signal, and the
            # stable key set across rows is what the agent actually wants
            # — that lives downstream in the columns we surface via
            # explode/normalize, not in a column-stats summary.
            kind = _container_kind(non_null.iloc[0])
            if kind == "list":
                col_type = "list"
                try:
                    lengths = non_null.map(_safe_len).dropna()
                    if not lengths.empty:
                        parts.append(f"items_min={int(lengths.min())}")
                        parts.append(f"items_max={int(lengths.max())}")
                        mean = float(lengths.mean())
                        parts.append(f"items_mean={_format_number(mean)}")
                except Exception:
                    pass
            else:  # struct
                col_type = "struct"
        elif not non_null.empty and _is_bytes_column(non_null):
            # Raw bytes columns (UDF returned bytes directly, or the
            # cells already went through cast_to_schema and are pickled
            # payloads). Two useful pieces of information: the SIZE
            # distribution (size_min/max/mean) and the SOURCE TYPE if
            # the cells carry the `pyobj@1\n` class-name header (cheap
            # fixed-offset peek — no unpickling).
            col_type = "binary"
            try:
                first_class = _embedded_class_name(non_null.iloc[0])
                if first_class:
                    parts.append(f"type={first_class}")
            except Exception:
                pass
            try:
                sizes = non_null.map(_safe_len).dropna()
                if not sizes.empty:
                    parts.append(f"size_min={int(sizes.min())}")
                    parts.append(f"size_max={int(sizes.max())}")
                    parts.append(f"size_mean={_format_number(float(sizes.mean()))}")
            except Exception:
                pass
        elif not non_null.empty and _is_binary_class_column(non_null):
            # Non-primitive Python objects (e.g. shapely Polygon cells
            # arriving BEFORE cast_to_schema turns them into bytes).
            # Stats fire on the pre-cast DataFrame, so the bytes path
            # above wouldn't trigger here — but the agent still wants
            # to see the Python type. Emit `(binary): null=N,
            # type=<module>.<class>`. No size info: pickling every
            # cell just for stats is too expensive on wide columns,
            # and the per-cell rendering already carries it.
            col_type = "binary"
            try:
                cls = type(non_null.iloc[0])
                parts.append(f"type={cls.__module__}.{cls.__qualname__}")
            except Exception:
                pass
        else:
            col_type = "str"
            # Cardinality via pandas' hash table — but the column may carry
            # unhashable cells (numpy.ndarray, list, dict, set) when a UDF
            # returns object-typed cells. `nunique()` then raises
            # `TypeError: unhashable type: 'numpy.ndarray'` outside user
            # code and torpedoes the entire stats-publishing chain. Cast
            # to str first so every cell is hashable; the resulting string
            # cardinality is what we already report for the str column
            # type anyway (the top_5 branch below uses the same .astype(str)
            # path). Fall back to a try/except symmetric with the numeric
            # branch above in case stringification itself fails on an
            # exotic cell type.
            distinct: Optional[int] = None
            try:
                distinct = int(non_null.astype(str).nunique())
                parts.append(f"distinct={distinct}")
            except Exception:
                pass
            # Only surface top_5 for low-cardinality string columns. The
            # cutoff (5) matches the head-size below; high-cardinality
            # columns (e.g. customer_id) get just null + distinct.
            if (
                distinct is not None
                and not non_null.empty
                and 0 < distinct <= 5
            ):
                try:
                    top = non_null.astype(str).value_counts().head(5)
                    inner = ", ".join(
                        f'"{k}"={int(v)}' for k, v in top.items()
                    )
                    parts.append(f"top_5={{{inner}}}")
                except Exception:
                    pass
            # Numeric values wearing formatting punctuation — currency
            # "$1,234", thousands "1,234", percent "45%", accounting
            # "(1,234)". Such a column arrived as str *because* the
            # punctuation blocked numeric parsing; a later
            # to_numeric(errors="coerce") then silently NULLs every formatted
            # value (e.g. "$1,234" -> NaN), dropping exactly the rows that
            # carry the data. Surface the format so the agent strips before
            # converting. Full-column, pandas-native (see _detect_numeric_format).
            try:
                fmt = DataProcessor._detect_numeric_format(non_null)
                if fmt is not None:
                    parts.append(f"format={fmt}")
            except Exception:
                pass

        return f"({col_type}): " + ", ".join(parts)

    @staticmethod
    def _detect_table_structure(df: pandas.DataFrame) -> list:
        """
        Name-agnostic STRUCTURAL profile of a DataFrame, surfaced as short
        pre-emptive hints at the operator boundary. Surface-only: the agent
        decides whether to act; nothing here mutates data. Mirrors the
        offline-validated probes in ``claude/profile_probe.py`` (see
        ``claude/PROBE-FINDINGS.md``). Every signal is pure cardinality / null
        structure, so it generalizes without keying on column names or task
        literals -- the same property that made ``_detect_numeric_format`` work
        where post-hoc surfacing levers did not.

        RAW FACTS ONLY (no classification bands, no semantic labels — per
        review, banded key/partition/group labeling was hand-authored judgment
        and was removed; per-column cardinality facts live in the columnStats
        block instead, and what to DO with them is the prompt's/model's call):
          - empty regions  -> exact all-null row/col counts (#25)
          - duplicate rows -> exact df.duplicated() count, shown when > 0 (#25)
          - unresolved header -> Unnamed:N placeholder count (pandas contract)

        Blank / ``Unnamed: N`` column names signal an unresolved header
        (skiprows/header=) and are surfaced via the header hint below.
        """
        try:
            n_rows = len(df)
            if n_rows == 0 or df.shape[1] == 0:
                return []
        except Exception:
            return []
        hints: list = []

        try:
            isna = df.isna()
            er = int(isna.all(axis=1).sum())
            null_cols = [str(c) for c in df.columns[isna.all(axis=0)]]
            if er:
                hints.append(f"empty rows: {er} of {n_rows} rows are entirely null")
            if null_cols:
                shown_cols = ", ".join(f'"{c}"' for c in null_cols[:8])
                more = f" (+{len(null_cols) - 8} more)" if len(null_cols) > 8 else ""
                hints.append(f"empty columns: [{shown_cols}]{more} are entirely null")
        except Exception:
            pass

        try:
            dups = int(df.duplicated().sum())
            if dups:
                hints.append(f"duplicate rows: {dups} of {n_rows} ({dups / n_rows:.0%})")
        except Exception:
            pass

        def _is_placeholder(name) -> bool:
            s = str(name).strip()
            return s == "" or s.startswith("Unnamed:")

        # Header-resolution hint (data-facet, load-quality). Blank / `Unnamed: N`
        # column names signal an UNRESOLVED header (the real header is not row 0
        # -- the file needs skiprows=/header=). This is a SILENT failure: the read
        # succeeds, so loader_hint (exception-keyed) never fires, yet downstream
        # column access is wrong. Surfacing it as an explicit remediation is the
        # pre-emptive counterpart to merely dropping these columns from the grain/
        # partition profile. Fires only when placeholders are a minority (a fully
        # headerless frame is a different, louder situation).
        try:
            n_cols = df.shape[1]
            n_placeholder = sum(1 for c in df.columns if _is_placeholder(c))
            if n_cols > 0 and 0 < n_placeholder < n_cols:
                ph = [str(c) for c in df.columns if _is_placeholder(c)]
                shown_ph = ", ".join(f'"{c}"' for c in ph[:6])
                hints.append(
                    f"headers: {n_placeholder} of {n_cols} columns are unnamed ({shown_ph})"
                )
        except Exception:
            pass

        return hints

    @staticmethod
    def _detect_numeric_format(non_null: pandas.Series) -> Optional[str]:
        """
        Decide whether an object/str column is really numeric values wearing
        formatting punctuation, and if so name the format. Returns one of
        ``"currency"`` / ``"thousands"`` / ``"percent"`` / ``"accounting"`` /
        ``"numeric-as-text"``, or ``None`` when the column is genuinely
        non-numeric text.

        Full-column and pandas-native — NOT a regex over a render-time
        preview sample. We let ``pandas.to_numeric`` be the judge on the whole
        column: a column qualifies only when stripping currency / grouping /
        percent punctuation (and mapping accounting parens to a leading minus)
        RECOVERS a large block of values that ``to_numeric`` misses as-is. That
        gate ("cleaning materially beats raw parsing AND ends up almost all
        numeric") is what separates a real $/comma-formatted number column from
        free text that happens to contain the odd numeral — without keying on
        any column name or task literal, so it generalizes.

        The dominant punctuation among the *rescued* values (those that parse
        only after cleaning) picks the tag, so the agent gets the specific
        cleaning to apply rather than a generic warning.
        """
        s = non_null.astype(str).str.strip()
        if len(s) < 2:
            return None
        raw = pandas.to_numeric(s, errors="coerce")
        raw_frac = float(raw.notna().mean())
        # Map accounting "(123)" -> "-123", then drop $, grouping commas,
        # percent signs and whitespace. ($ is literal inside the char class.)
        cleaned_str = s.str.replace(r"^\((.*)\)$", r"-\1", regex=True).str.replace(
            r"[$,%\s]", "", regex=True
        )
        cleaned = pandas.to_numeric(cleaned_str, errors="coerce")
        clean_frac = float(cleaned.notna().mean())
        # Two gates:
        #   clean_frac >= 0.8 — the column is predominantly numeric once cleaned,
        #     i.e. a number column, not free text. (Set at 0.8 rather than higher
        #     because raw loader output routinely mixes a header/footer row or
        #     two into a data column — "# of Reports", "Source: ..." — which are
        #     real strings that drag the parse fraction down without changing
        #     what the column *is*.)
        #   delta >= 0.1 — a material block (>=10%) of values parse ONLY after
        #     cleaning. Since cleaning only ever adds parses (clean superset of
        #     raw), delta == the rescued fraction: the formatted values a naive
        #     to_numeric(coerce) would silently NULL. A plain digit-string column
        #     parses raw (delta ~ 0) and is correctly NOT flagged.
        if clean_frac < 0.8 or clean_frac - raw_frac < 0.1:
            return None
        rescued = s[cleaned.notna() & raw.isna()]
        if rescued.empty:
            rescued = s
        # $ before commas: currency usually carries both, and $ is the more
        # specific signal. Parens before commas for the same reason.
        if float(rescued.str.contains("$", regex=False).mean()) >= 0.5:
            return "currency"
        if float(rescued.str.contains("%", regex=False).mean()) >= 0.5:
            return "percent"
        if float(rescued.str.match(r"^\(.*\)$").mean()) >= 0.5:
            return "accounting"
        if float(rescued.str.contains(",", regex=False).mean()) >= 0.5:
            return "thousands"
        return "numeric-as-text"

