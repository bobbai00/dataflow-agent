# Matches user-UDF source files generated by ExecutorManager (udf-v1.py,
# udf-v2.py, ...). Used to locate the user's frame in a traceback.
_UDF_FILENAME_PATTERN = re.compile(r"^udf-v\d+\.py$")


# Pandas dtype name → AttributeType. Object columns are sampled separately to
# distinguish STRING / LIST / STRUCT.
_PANDAS_DTYPE_TO_ATTRIBUTE_TYPE: Dict[str, AttributeType] = {
    "int8": AttributeType.LONG,
    "int16": AttributeType.LONG,
    "int32": AttributeType.LONG,
    "int64": AttributeType.LONG,
    "uint8": AttributeType.LONG,
    "uint16": AttributeType.LONG,
    "uint32": AttributeType.LONG,
    "uint64": AttributeType.LONG,
    "float16": AttributeType.DOUBLE,
    "float32": AttributeType.DOUBLE,
    "float64": AttributeType.DOUBLE,
    "bool": AttributeType.BOOL,
    "datetime64[ns]": AttributeType.TIMESTAMP,
    "datetime64[us]": AttributeType.TIMESTAMP,
    "datetime64[ms]": AttributeType.TIMESTAMP,
}


def _to_dataframe(output: Any) -> Optional[pandas.DataFrame]:
    """
    Coerce a Table-API yield to a pandas DataFrame for inference + profiling.
    Returns None for tuple-yielding outputs (TupleLike), None values, or any
    other object — those flow through the existing tuple path unchanged.
    """
    if isinstance(output, pandas.DataFrame):
        return output
    if isinstance(output, pa.Table):
        return output.to_pandas()
    # Texera Table model exposes to_pandas() — duck-typed.
    if hasattr(output, "to_pandas") and callable(getattr(output, "to_pandas")):
        try:
            df = output.to_pandas()
            if isinstance(df, pandas.DataFrame):
                return df
        except Exception:
            return None
    return None


class DataProcessor(Runnable, Stoppable):
    def __init__(self, context: Context):
        self._running = Event()
        self._context = context
        # Set to True after the first DataFrame yield triggers schema
        # inference + (optional) port rewrite. Subsequent yields skip the
        # inference work and reuse whatever port schema is now active.
        self._schema_inferred: bool = False
        self._table_profile = None

    def run(self) -> None:
        """
        Start the data processing loop. Wait for context switch conditions to be met,
        then continuously process markers or tuples until stopped.
        """
        with self._context.tuple_processing_manager.context_switch_condition:
            self._context.tuple_processing_manager.context_switch_condition.wait()
        self._running.set()
        self._check_and_process_debug_command()
        while self._running.is_set():
            tpm = self._context.tuple_processing_manager
            spm = self._context.state_processing_manager
            has_marker = tpm.current_internal_marker is not None
            has_state = spm.current_input_state is not None
            has_tuple = tpm.current_input_tuple is not None
            # MainLoop is single-threaded and sets at most one of
            # current_internal_marker / current_input_state /
            # current_input_tuple per cycle before switching to here, so
            # exactly one slot must be populated on every iteration.
            if has_marker + has_state + has_tuple != 1:
                raise RuntimeError(
                    "DataProcessor expected exactly one queued input per "
                    f"iteration, got marker={has_marker}, state={has_state}, "
                    f"tuple={has_tuple}"
                )
            if has_marker:
                self.process_internal_marker(tpm.get_internal_marker())
            elif has_state:
                self.process_state(spm.get_input_state())
            else:
                self.process_tuple()

    def process_internal_marker(self, internal_marker: InternalMarker) -> None:
        with self._executor_session() as (executor, port_id):
            if isinstance(internal_marker, StartChannel):
                self._set_output_state(executor.produce_state_on_start(port_id))
            elif isinstance(internal_marker, EndChannel):
                # Empty streams still carry a port schema. Tuples cannot
                # convey it when no rows arrive, so pass the latest runtime
                # schema before table/state callbacks materialize the buffer.
                input_port = self._context.tuple_processing_manager.current_input_port_id
                if isinstance(executor, TableOperator) and input_port is not None:
                    executor._set_input_schema(port_id, self._context.input_manager.get_port(input_port).get_schema())
                self._set_output_state(executor.produce_state_on_finish(port_id))
                # Flush the state to MainLoop before producing tuples so the
                # state and the tuple stream don't share a single switch.
                self._switch_context()
                self._set_output_tuple(executor.on_finish(port_id))

    def process_state(self, state: State) -> None:
        """
        Process an input marker by invoking appropriate state
        or tuple generation based on the marker type.
        """
        with self._executor_session() as (executor, port_id):
            self._set_output_state(executor.process_state(state, port_id))

    def process_tuple(self) -> None:
        """
        Process an input tuple by invoking the executor's tuple processing method.
        """
        finished_current = self._context.tuple_processing_manager.finished_current
        while not finished_current.is_set():
            with self._executor_session() as (executor, port_id):
                tuple_ = self._context.tuple_processing_manager.get_input_tuple()
                self._set_output_tuple(executor.process_tuple(tuple_, port_id))

    @contextmanager
    def _executor_session(self):
        """
        Open one executor invocation: hand back (executor, port_id) under a
        print-capture session, route any exception to the exception manager
        and queue the stack trace as a console message, and always switch
        back to MainLoop on exit. Reporting must happen *before* the
        switch: MainLoop's post-switch hook flushes console messages and
        then enters EXCEPTION_PAUSE, so anything queued after the switch
        would arrive at the coordinator only after the worker resumes.
        """
        try:
            executor = self._context.executor_manager.executor
            port_id = self._context.tuple_processing_manager.get_input_port_id()
            with replace_print(
                self._context.worker_id,
                self._context.console_message_manager.print_buf,
            ):
                yield executor, port_id
        except Exception as err:
            logger.exception(err)
            exc_info = sys.exc_info()
            self._context.exception_manager.set_exception_info(exc_info)
            # UDF data-path errors use the user-code-locating reporter
            # (_report_exception): exception type+message, the UDF's failing
            # line, and the operator source — with the engine's internal
            # multi-frame traceback intentionally omitted. #5783 had
            # centralized this onto create_error_console_message, which dumped
            # the raw engine traceback (data_processor/tuple frames + embedded
            # data) that the agent cannot act on. Restored here so the agent
            # sees its own code + line, not engine internals.
            self._report_exception(exc_info)
        finally:
            self._switch_context()

    def _set_output_tuple(self, output_iterator: Iterator[Optional[TupleLike]]) -> None:
        """
        Set the output tuple after processing by the executor.
        """
        for output in output_iterator:
            # output could be a None, a TupleLike, or a TableLike.
            self._maybe_apply_runtime_schema(output)
            whole = self._arrow_output(output)
            if whole is not None:
                # The rows now live in `whole`: let the frame go before they
                # are sent and written (2.9 GB for an 8.6 M-row scan).
                output = None
                self._switch_context()
                self._context.tuple_processing_manager.current_output_tuple = whole
                self._switch_context()
                continue
            for output_tuple in all_output_to_tuple(output):
                if output_tuple is not None:
                    output_tuple.finalize(
                        self._context.output_manager.get_port().get_schema()
                    )
                self._switch_context()
                self._context.tuple_processing_manager.current_output_tuple = (
                    output_tuple
                )
                self._switch_context()
        self._context.tuple_processing_manager.finished_current.set()

    def _arrow_output(self, output: Any) -> Optional[ArrowOutput]:
        """A yielded DataFrame as one Arrow table, when its rows may leave
        whole (``OutputManager.accepts_arrow``) and every column already
        holds the port's type (``frame_to_arrow``): no Tuple, cast, type
        check and size walk per row. None keeps the per-row path, which also
        reports any row that does not fit the schema. Loop operators keep it."""
        if not isinstance(output, pandas.DataFrame) or len(output) == 0:
            return None
        if isinstance(self._context.executor_manager.executor, (LoopStartOperator, LoopEndOperator)):
            return None
        output_manager = self._context.output_manager
        if not output_manager.accepts_arrow():
            return None
        try:
            table = frame_to_arrow(output, output_manager.get_port().get_schema())
        except Exception:
            return None
        return ArrowOutput(table) if table is not None else None

    # ------------------------------------------------------------------
    # Runtime schema inference + per-column profiling (Table API only)
    # ------------------------------------------------------------------

    def _maybe_apply_runtime_schema(self, output: Any) -> None:
        """
        Table-API path. On the first yielded DataFrame, infer the schema from
        the DataFrame's dtypes and reconcile against the declared port schema:
          - declared empty → silently rewrite port + recreate writers
          - declared non-empty + mismatch → raise (UDF contract violation)
          - declared non-empty + match → no-op
        Subsequent yields skip inference and reuse the now-active port
        schema; every yield is still added to the table's statistics. No-op
        for non-Table yields (tuple-yielding UDFs must declare their schema
        upfront).
        """
        df = _to_dataframe(output)
        if df is None:
            return

        if not self._schema_inferred:
            self._schema_inferred = True
            inferred = self._infer_schema_from_dataframe(df)
            declared = self._context.output_manager.get_port().get_schema()
            if inferred != declared:
                if declared.get_attr_names():
                    # Static-schema operator (e.g. PythonUDFV2): the declared
                    # schema is authoritative. Before rejecting, bridge benign
                    # numeric discrepancies that Tuple.cast_to_schema fixes per
                    # cell — chiefly a nullable integer column that round-trips
                    # through pandas as float64 (pandas int64 cannot hold
                    # nulls). For those, keep the declared schema and let
                    # finalize() coerce DOUBLE→LONG (NaN→None). Only a genuine
                    # mismatch (changed columns, fractional data declared as an
                    # integer, or a non-numeric type change) still raises.
                    if not self._numeric_mismatch_is_bridgeable(
                        df, declared, inferred
                    ):
                        raise RuntimeError(
                            f"Output schema mismatch: declared {declared}, "
                            f"got {inferred}."
                        )
                    logger.info(
                        "Bridged benign numeric schema discrepancy against "
                        f"declared schema {declared} (inferred {inferred})."
                    )
                else:
                    self._context.output_manager.get_port().set_schema(inferred)
                    for port_id in self._context.output_manager.get_port_ids():
                        self._context.output_manager.recreate_port_storage_writer(
                            port_id, inferred
                        )
                    logger.info(
                        f"Schema inferred from DataFrame dtypes: {inferred}"
                    )

        self._publish_table_profile(df)

    @staticmethod
    def _numeric_mismatch_is_bridgeable(
        df: pandas.DataFrame, declared: Schema, inferred: Schema
    ) -> bool:
        """
        True when every column where `inferred` differs from `declared` is a
        benign numeric discrepancy that `Tuple.cast_to_schema` bridges per
        cell, so the declared schema can stand unchanged:

          - declared INT/LONG vs inferred DOUBLE → bridgeable only when the
            column's non-null values are all integral. This is the common
            "nullable integer column arrives in pandas as float64" case
            (pandas int64 cannot hold NaN); cast_to_schema maps NaN→None and
            integer-valued floats→int.
          - any other pair within {INT, LONG, DOUBLE} → bridgeable (lossless,
            e.g. INT→LONG, or int values declared DOUBLE).

        Anything else — a changed/missing/extra/reordered column, a
        non-numeric type change (e.g. STRING↔LONG), or genuinely fractional
        data declared as an integer — is NOT bridgeable and stays a hard
        mismatch so real UDF contract violations still surface.
        """
        numeric = (AttributeType.INT, AttributeType.LONG, AttributeType.DOUBLE)
        declared_names = declared.get_attr_names()
        if declared_names != inferred.get_attr_names():
            return False
        for name in declared_names:
            declared_type = declared.get_attr_type(name)
            inferred_type = inferred.get_attr_type(name)
            if declared_type == inferred_type:
                continue
            if declared_type not in numeric or inferred_type not in numeric:
                return False
            # Narrowing a float column to an integer type is only safe when
            # the observed values carry no fractional part.
            if (
                declared_type in (AttributeType.INT, AttributeType.LONG)
                and inferred_type == AttributeType.DOUBLE
            ):
                col = pandas.to_numeric(df[name], errors="coerce").dropna()
                if len(col) and not (col == col.round()).all():
                    return False
        return True

    def _infer_schema_from_dataframe(self, df: pandas.DataFrame) -> Schema:
        """
        Build a Texera Schema from a pandas DataFrame's dtypes. Object
        columns are handed off to `_infer_type_from_object_column`, which
        runs a whole-column `pandas.api.types.infer_dtype` scan (handles
        nulls and mixed-numeric properly); other dtypes go through
        `_map_pandas_dtype_to_attribute_type`, which understands pandas
        extension dtypes (Int64/Float64/boolean/string/categorical/
        timedelta64) and the numpy primitives.

        Column-name handling matches `Table.as_tuples`: labels are
        stringified (a `pd.read_excel(header=None)` DataFrame carries int
        RangeIndex labels) and deduplicated (two columns called "x" become
        "x" and "x.1") so the inferred Schema lines up cell-for-cell with
        the deduped Tuples produced downstream. Columns are read
        positionally via `df.iloc[:, i]` rather than `df[name]` so a
        duplicate label doesn't return a DataFrame instead of a Series
        (which would `AttributeError` on `.dtype`).
        """
        from core.models.table import deduplicate_columns

        str_columns = [str(c) for c in df.columns]
        deduped_columns, _ = deduplicate_columns(str_columns)
        schema = Schema()
        for i, col_name in enumerate(deduped_columns):
            col = df.iloc[:, i]
            if pandas.api.types.is_object_dtype(col):
                attr_type = self._infer_type_from_object_column(col)
            else:
                attr_type = self._map_pandas_dtype_to_attribute_type(col.dtype)
            schema.add(col_name, attr_type)
        return schema

    @staticmethod
    def _infer_type_from_object_column(col: pandas.Series) -> AttributeType:
        """
        Infer an AttributeType for an object-dtype column. Uses pandas'
        `infer_dtype` so a column of `[1, None, 2]` types as LONG (not
        whatever the first non-null cell happens to be) and a column of
        `[1, 1.5, None]` types as DOUBLE.

        Falls back to type-sampling when pandas reports `mixed` (or one of
        the catch-all kinds): up to 100 non-null values are inspected, and
        a column is LIST/STRUCT only when *every* sampled value is a list
        or dict respectively. Anything else (truly mixed, or unknown kind
        with no values to sample) falls back to STRING, which is the
        safest type for downstream serialization.
        """
        inferred = pandas.api.types.infer_dtype(col, skipna=True)

        if inferred == "integer":
            return AttributeType.LONG
        if inferred == "floating" or inferred == "mixed-integer-float":
            # Floats can represent ints, so a mix of the two is still DOUBLE.
            return AttributeType.DOUBLE
        if inferred == "boolean":
            return AttributeType.BOOL
        if inferred == "string":
            return AttributeType.STRING
        if inferred == "bytes":
            return AttributeType.BINARY
        if inferred in ("datetime", "datetime64", "date"):
            return AttributeType.TIMESTAMP

        non_null = col.dropna()
        if non_null.empty:
            return AttributeType.STRING

        sample = non_null.head(100)
        types_seen = set(type(v) for v in sample)
        if types_seen == {list}:
            return AttributeType.LIST
        if types_seen == {dict}:
            return AttributeType.STRUCT
        if types_seen == {bytes} or types_seen == {bytearray}:
            return AttributeType.BINARY
        return AttributeType.STRING

    @staticmethod
    def _map_pandas_dtype_to_attribute_type(dtype) -> AttributeType:
        """
        Map a numpy/pandas dtype to an AttributeType. Covers numpy primitives
        via the lookup table, then falls back to string-name matching for
        pandas extension dtypes (capitalized nullable types, StringDtype,
        CategoricalDtype, datetime64 with tz, timedelta64). Unknown dtypes
        default to BINARY, which gets pickled downstream.
        """
        dtype_str = str(dtype)
        if dtype_str in _PANDAS_DTYPE_TO_ATTRIBUTE_TYPE:
            return _PANDAS_DTYPE_TO_ATTRIBUTE_TYPE[dtype_str]
        # Pandas nullable integer types: Int8/Int16/Int32/Int64, UInt8…UInt64.
        if dtype_str.startswith("Int") or dtype_str.startswith("UInt"):
            return AttributeType.LONG
        # Pandas nullable float types: Float32, Float64.
        if dtype_str.startswith("Float"):
            return AttributeType.DOUBLE
        # Pandas nullable boolean.
        if dtype_str == "boolean":
            return AttributeType.BOOL
        # Pandas StringDtype, under any spelling ("string", "string[pyarrow]",
        # or pandas 3's default "str"). A new name must not turn text into
        # pickled bytes: the agent then sees "<builtins.str, size = 55 bytes>".
        if dtype_str == "string" or pandas.api.types.is_string_dtype(dtype):
            return AttributeType.STRING
        # Categorical — stringify the categories for downstream consumption.
        if hasattr(dtype, "categories"):
            return AttributeType.STRING
        # datetime64 with or without tz (e.g. "datetime64[ns, UTC]").
        if dtype_str.startswith("datetime64") or hasattr(dtype, "tz"):
            return AttributeType.TIMESTAMP
        # timedelta64 — store as int nanoseconds.
        if dtype_str.startswith("timedelta64"):
            return AttributeType.LONG
        logger.debug(f"Unknown pandas dtype {dtype_str!r}, defaulting to BINARY")
        return AttributeType.BINARY

    def _publish_table_profile(self, df: pandas.DataFrame) -> None:
        """
        Add the yielded table to its native profile, when the operator asked
        for one (`profileCollection`), and publish the profile so far under its
        reserved key so it rides out on the next WorkerStatistics emission.
        """
        metadata = df.attrs.get("native_v2")
        if self._table_profile is None:
            if (
                not isinstance(metadata, dict)
                or metadata.get("profileCollection") is not True
            ):
                return
            try:
                from core.util.table_profile import ProfileAccumulator

                self._table_profile = ProfileAccumulator(
                    self._context.worker_id, metadata
                )
            except Exception:
                # A partial worker deployment must not fail a valid data result.
                # Missing telemetry is reported as unavailable by the consumer.
                return
        try:
            self._table_profile.add(df)
        except Exception:
            self._table_profile.fail("profiler_error")
        self._store_table_profile()

    def _store_table_profile(self) -> None:
        if self._table_profile is not None:
            try:
                self._context.statistics_manager.set_profile_statistics(
                    self._table_profile.key, self._table_profile.encode()
                )
            except Exception:
                # Optional telemetry failure never fails the table execution.
                # The consumer treats a missing envelope as unavailable.
                pass

    def finish_table_profile(self) -> None:
        if self._table_profile is not None:
            self._table_profile.finish()
            self._store_table_profile()

    def _set_output_state(self, output_state: State) -> None:
        """
        Set the output state after processing by the executor.
        """
        if output_state is not None and not isinstance(output_state, State):
            output_state = State(output_state)
        self._context.state_processing_manager.current_output_state = output_state

    def _switch_context(self) -> None:
        """
        Notify the MainLoop thread and wait here until being switched back.
        """
        with self._context.tuple_processing_manager.context_switch_condition:
            self._context.tuple_processing_manager.context_switch_condition.notify()
            self._context.tuple_processing_manager.context_switch_condition.wait()
        self._check_and_process_debug_command()

    def _check_and_process_debug_command(self) -> None:
        """
        If a debug command is available, invokes the debugger from this frame.
        """
        if self._context.debug_manager.has_debug_command():
            # Let debugger trace from the current frame.
            # This line will also trigger cmdloop in the debugger.
            # This line has no side effects on the current debugger state.
            self._context.debug_manager.debugger.set_trace()

    @staticmethod
    def _find_user_code_frame(tb):
        """
        Walk the traceback (deepest first) to find the last frame that belongs
        to a user UDF file (udf-v*.py). Returns (frame, user_line_number) where
        user_line_number is adjusted so the first line of the user's function
        body is line 1. Returns (None, None) if no UDF frame is found.
        """
        for frame in reversed(tb):
            base_name = os.path.basename(frame.filename)
            if _UDF_FILENAME_PATTERN.match(base_name):
                user_line = frame.lineno
                try:
                    with open(frame.filename, "r") as f:
                        for i, line in enumerate(f, start=1):
                            stripped = line.strip()
                            if stripped.startswith(
                                f"def {frame.name}("
                            ) or stripped.startswith(f"def {frame.name} ("):
                                user_line = frame.lineno - i + 1
                                break
                except OSError:
                    pass
                return frame, user_line
        return None, None

    @staticmethod
    def _read_udf_source(filename: str) -> Optional[str]:
        """
        Read a user UDF file end-to-end. Returns None if the file cannot be
        opened (e.g., already deleted, or permissions); callers fall back to
        the short error message.
        """
        try:
            with open(filename, "r") as f:
                return f.read()
        except OSError:
            return None

    @staticmethod
    def _slice_user_code(source: str) -> "tuple[list[str], int]":
        """
        For the wrapped DataLoading / DataProcessing UDFs, the source has the
        shape:

            from pytexera import *           # boilerplate
            import pandas as pd              # boilerplate
                                             # boilerplate
            class GenerateOperator(...)/     # boilerplate (indented body)
            class ProcessTablesOperator(...) # boilerplate (indented body)
                ...
            def load(...) -> ...:            # <-- user code starts here
                ...

        The user's `def load()` / `def process()` is the first *top-level*
        `def` (column 0) — the wrapper class methods are all indented. Slice
        the source to start at that line so the agent sees only what it
        actually wrote, and so line numbers are user-relative (line 1 = the
        user's def).

        Returns (lines_starting_at_user_def, offset) where `offset` is the
        absolute line index (1-based) of the first user line — used to
        translate the absolute traceback line into a user-relative one.
        Returns (all_lines, 0) for sources that don't match the wrapping
        pattern (e.g. raw PythonUDFV2 user code), preserving the old
        full-file behavior for those.
        """
        lines = source.splitlines()
        for i, line in enumerate(lines):
            stripped = line.lstrip()
            if stripped.startswith("def ") and line[: len(line) - len(stripped)] == "":
                # First column-0 `def` — this is the user's function.
                return lines[i:], i + 1
        return lines, 0

    def _report_exception(self, exc_info: ExceptionInfo):
        tb = traceback.extract_tb(exc_info[2])
        exception_type = type(exc_info[1]).__name__
        exception_msg = str(exc_info[1])

        # Truncate the code line (often the longest part) rather than the
        # whole title, so the error type/message is always preserved.
        def _clip(s: str, n: int) -> str:
            return s if len(s) <= n else s[: max(0, n - 1)] + "…"

        # Middle-clip for the exception MESSAGE. Some framework exceptions embed
        # a full DataFrame repr (e.g. tuple.py's schema-mismatch KeyError dumps
        # the offending Tuple), and the actionable text ("unexpected field 'X'")
        # sits at the END — so head-only truncation would drop it. Keep head+tail.
        def _clip_middle(s: str, head: int, tail: int) -> str:
            if len(s) <= head + tail + 40:
                return s
            return f"{s[:head]} …[{len(s) - head - tail} chars elided]… {s[-tail:]}"

        # Only the generated single-function wrappers — DataProcessing
        # (UDFMultiTableOperator) and DataLoading (UDFSourceOperator) — get
        # user-code line locating + function slicing: we authored the wrapper,
        # so the user wrote exactly one function and the traceback maps cleanly
        # to their line. Hand-written operators (PythonUDFV2 / UDFOperatorV2)
        # own the whole class, where a single "user line" is misleading — hand
        # back the full multi-frame traceback (plus the operator's code).
        if not self._operator_uses_line_locating():
            self._report_full_traceback(exc_info, tb, exception_type, exception_msg, _clip)
            return

        udf_frame, user_line = self._find_user_code_frame(tb)
        full_source: Optional[str] = None
        if udf_frame is not None:
            code_line = udf_frame.line
            base_name = os.path.basename(udf_frame.filename)
            module_name, _ = os.path.splitext(base_name)
            source = f"{module_name}:{udf_frame.name}:{udf_frame.lineno}"
            if code_line:
                title = (
                    f"(line {user_line}) `{_clip(code_line.strip(), 200)}` "
                    f"- {exception_type}: {exception_msg}"
                )
            else:
                title = f"(line {user_line}) {exception_type}: {exception_msg}"
            full_source = self._read_udf_source(udf_frame.filename)
        else:
            # No user-UDF frame on the traceback — the exception was raised
            # in framework code (e.g. schema validation after `def load()`
            # returned). The deepest frame's code line (`raise TypeError(`)
            # is meaningless to the agent, so use the exception message
            # itself as the title.
            filename, line_number, func_name, _ = tb[-1]
            base_name = os.path.basename(filename)
            module_name, _ = os.path.splitext(base_name)
            source = f"{module_name}:{func_name}:{line_number}"
            title = f"{exception_type}: {_clip(exception_msg, 400)}"

        # Build the message. The multi-frame traceback is intentionally
        # omitted, and — matching the pre-refactor behavior — the operator's
        # SOURCE CODE is NOT echoed into the error message either: the
        # agent-service renders the errored operator's code in the assembled
        # context (it owns the code via operatorProperties), so repeating it
        # here would double the token cost of every error. What the agent
        # needs from the engine is the exception line plus the user-code
        # line pointer:
        #   1. the exception type + middle-clipped message,
        #   2. `at line N in <func>` when a user-UDF frame was on the
        #      traceback (the failing line's TEXT is already in the title).
        parts: List[str] = [f"{exception_type}: {_clip_middle(exception_msg, 400, 300)}"]

        if full_source is not None and udf_frame is not None:
            user_lines, offset = self._slice_user_code(full_source)
            if user_lines:
                error_line_in_slice = (
                    udf_frame.lineno - offset + 1 if offset > 0 else udf_frame.lineno
                )
                parts.append(f"  at line {error_line_in_slice} in `{udf_frame.name}`")

        message = "\n".join(parts)

        self._context.console_message_manager.put_message(
            ConsoleMessage(
                worker_id=self._context.worker_id,
                timestamp=current_time_in_local_timezone(),
                msg_type=ConsoleMessageType.ERROR,
                source=source,
                title=title,
                message=message,
            )
        )

    def _operator_uses_line_locating(self) -> bool:
        """
        True when the running operator is a generated single-function wrapper:
        DataProcessing (UDFMultiTableOperator) or DataLoading
        (UDFSourceOperator). Those get user-code line locating; every other
        operator (PythonUDFV2 / UDFOperatorV2, …) gets the full traceback.

        Imported lazily to avoid a core→pytexera import cycle at module load;
        any failure conservatively falls back to the full-traceback path.
        """
        try:
            from pytexera.udf.udf_multi_table_operator import UDFMultiTableOperator
            from pytexera.udf.udf_operator import UDFSourceOperator
        except Exception:
            return False
        executor = getattr(
            getattr(self._context, "executor_manager", None), "executor", None
        )
        return isinstance(executor, (UDFMultiTableOperator, UDFSourceOperator))

    def _report_full_traceback(
        self,
        exc_info: ExceptionInfo,
        tb,
        exception_type: str,
        exception_msg: str,
        clip,
    ) -> None:
        """
        Error reporting for hand-written operators (e.g. PythonUDFV2): emit the
        complete multi-frame Python traceback as the message. No user-relative
        line locating — the user owns the whole operator class, so the raw
        stack is the faithful signal. The operator's SOURCE is intentionally
        not echoed (the agent-service renders errored operators' code in the
        assembled context from operatorProperties).
        """
        if tb:
            filename, line_number, func_name, _ = tb[-1]
            base_name = os.path.basename(filename)
            module_name, _ = os.path.splitext(base_name)
            source = f"{module_name}:{func_name}:{line_number}"
        else:
            source = ""
        title = f"{exception_type}: {clip(exception_msg, 400)}"

        message = "".join(traceback.format_exception(*exc_info)).rstrip()

        self._context.console_message_manager.put_message(
            ConsoleMessage(
                worker_id=self._context.worker_id,
                timestamp=current_time_in_local_timezone(),
                msg_type=ConsoleMessageType.ERROR,
                source=source,
                title=title,
                message=message,
            )
        )

    def stop(self):
        self._running.clear()
