    @staticmethod
    def _slice_user_code(source: str) -> "tuple[list[str], int]":
        """
        For the wrapped DataLoading / DataProcessing UDFs, the source has the
        shape:

            from pytexera import *           # boilerplate
            import pandas as pd              # boilerplate
                                             # boilerplate
            class GenerateOperator(...)/     # boilerplate (indented body)
            class ProcessTablesOperator(...) # boilerplate (indented body)
                ...
            def load(...) -> ...:            # <-- user code starts here
                ...

        The user's `def load()` / `def process()` is the first *top-level*
        `def` (column 0) — the wrapper class methods are all indented. Slice
        the source to start at that line so the agent sees only what it
        actually wrote, and so line numbers are user-relative (line 1 = the
        user's def).

        Returns (lines_starting_at_user_def, offset) where `offset` is the
        absolute line index (1-based) of the first user line — used to
        translate the absolute traceback line into a user-relative one.
        Returns (all_lines, 0) for sources that don't match the wrapping
        pattern (e.g. raw PythonUDFV2 user code), preserving the old
        full-file behavior for those.
        """
        lines = source.splitlines()
        for i, line in enumerate(lines):
            stripped = line.lstrip()
            if stripped.startswith("def ") and line[: len(line) - len(stripped)] == "":
                # First column-0 `def` — this is the user's function.
                return lines[i:], i + 1
        return lines, 0

    def _report_exception(self, exc_info: ExceptionInfo):
        tb = traceback.extract_tb(exc_info[2])
        exception_type = type(exc_info[1]).__name__
        exception_msg = str(exc_info[1])

        # Truncate the code line (often the longest part) rather than the
        # whole title, so the error type/message is always preserved.
        def _clip(s: str, n: int) -> str:
            return s if len(s) <= n else s[: max(0, n - 1)] + "…"

        # Middle-clip for the exception MESSAGE. Some framework exceptions embed
        # a full DataFrame repr (e.g. tuple.py's schema-mismatch KeyError dumps
        # the offending Tuple), and the actionable text ("unexpected field 'X'")
        # sits at the END — so head-only truncation would drop it. Keep head+tail.
        def _clip_middle(s: str, head: int, tail: int) -> str:
            if len(s) <= head + tail + 40:
                return s
            return f"{s[:head]} …[{len(s) - head - tail} chars elided]… {s[-tail:]}"

        # Only the generated single-function wrappers — DataProcessing
        # (UDFMultiTableOperator) and DataLoading (UDFSourceOperator) — get
        # user-code line locating + function slicing: we authored the wrapper,
        # so the user wrote exactly one function and the traceback maps cleanly
        # to their line. Hand-written operators (PythonUDFV2 / UDFOperatorV2)
        # own the whole class, where a single "user line" is misleading — hand
        # back the full multi-frame traceback (plus the operator's code).
        if not self._operator_uses_line_locating():
            self._report_full_traceback(exc_info, tb, exception_type, exception_msg, _clip)
            return

        udf_frame, user_line = self._find_user_code_frame(tb)
        full_source: Optional[str] = None
        if udf_frame is not None:
            code_line = udf_frame.line
            base_name = os.path.basename(udf_frame.filename)
            module_name, _ = os.path.splitext(base_name)
            source = f"{module_name}:{udf_frame.name}:{udf_frame.lineno}"
            if code_line:
                title = (
                    f"(line {user_line}) `{_clip(code_line.strip(), 200)}` "
                    f"- {exception_type}: {exception_msg}"
                )
            else:
                title = f"(line {user_line}) {exception_type}: {exception_msg}"
            full_source = self._read_udf_source(udf_frame.filename)
        else:
            # No user-UDF frame on the traceback — the exception was raised
            # in framework code (e.g. schema validation after `def load()`
            # returned). The deepest frame's code line (`raise TypeError(`)
            # is meaningless to the agent, so use the exception message
            # itself as the title.
            filename, line_number, func_name, _ = tb[-1]
            base_name = os.path.basename(filename)
            module_name, _ = os.path.splitext(base_name)
            source = f"{module_name}:{func_name}:{line_number}"
            title = f"{exception_type}: {_clip(exception_msg, 400)}"

        # Build the message. The multi-frame traceback is intentionally
        # omitted, and — matching the pre-refactor behavior — the operator's
        # SOURCE CODE is NOT echoed into the error message either: the
        # agent-service renders the errored operator's code in the assembled
        # context (it owns the code via operatorProperties), so repeating it
        # here would double the token cost of every error. What the agent
        # needs from the engine is the exception line plus the user-code
        # line pointer:
        #   1. the exception type + middle-clipped message,
        #   2. `at line N in <func>` when a user-UDF frame was on the
        #      traceback (the failing line's TEXT is already in the title).
        parts: List[str] = [f"{exception_type}: {_clip_middle(exception_msg, 400, 300)}"]

        if full_source is not None and udf_frame is not None:
            user_lines, offset = self._slice_user_code(full_source)
            if user_lines:
                error_line_in_slice = (
                    udf_frame.lineno - offset + 1 if offset > 0 else udf_frame.lineno
                )
                parts.append(f"  at line {error_line_in_slice} in `{udf_frame.name}`")

        message = "\n".join(parts)

        self._context.console_message_manager.put_message(
            ConsoleMessage(
                worker_id=self._context.worker_id,
                timestamp=current_time_in_local_timezone(),
                msg_type=ConsoleMessageType.ERROR,
                source=source,
                title=title,
                message=message,
            )
        )

    def _operator_uses_line_locating(self) -> bool:
        """
        True when the running operator is a generated single-function wrapper:
        DataProcessing (UDFMultiTableOperator) or DataLoading
        (UDFSourceOperator). Those get user-code line locating; every other
        operator (PythonUDFV2 / UDFOperatorV2, …) gets the full traceback.

        Imported lazily to avoid a core→pytexera import cycle at module load;
        any failure conservatively falls back to the full-traceback path.
        """
        try:
            from pytexera.udf.udf_multi_table_operator import UDFMultiTableOperator
            from pytexera.udf.udf_operator import UDFSourceOperator
        except Exception:
            return False
        executor = getattr(
            getattr(self._context, "executor_manager", None), "executor", None
        )
        return isinstance(executor, (UDFMultiTableOperator, UDFSourceOperator))

    def _report_full_traceback(
        self,
        exc_info: ExceptionInfo,
        tb,
        exception_type: str,
        exception_msg: str,
        clip,
    ) -> None:
        """
        Error reporting for hand-written operators (e.g. PythonUDFV2): emit the
        complete multi-frame Python traceback as the message. No user-relative
        line locating — the user owns the whole operator class, so the raw
        stack is the faithful signal. The operator's SOURCE is intentionally
        not echoed (the agent-service renders errored operators' code in the
        assembled context from operatorProperties).
        """
        if tb:
            filename, line_number, func_name, _ = tb[-1]
            base_name = os.path.basename(filename)
            module_name, _ = os.path.splitext(base_name)
            source = f"{module_name}:{func_name}:{line_number}"
        else:
            source = ""
        title = f"{exception_type}: {clip(exception_msg, 400)}"

        message = "".join(traceback.format_exception(*exc_info)).rstrip()

        self._context.console_message_manager.put_message(
            ConsoleMessage(
                worker_id=self._context.worker_id,
                timestamp=current_time_in_local_timezone(),
                msg_type=ConsoleMessageType.ERROR,
                source=source,
                title=title,
                message=message,
            )
        )

    def stop(self):
        self._running.clear()
