/** Render the current native-mode prompt, tool, and operator contracts. */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { asSchema } from "ai";
import { ContextMode } from "../src/types/agent";
import { buildRegisteredNativeSystemPrompt } from "../src/agent/prompts";
import { registeredCatalogText } from "../src/agent/native/registered";
import { createDataflowTool } from "../src/agent/tools/turn-tool";

const root = fileURLToPath(new URL("../../native-mode/", import.meta.url));
const HEADER = (title: string, what: string) =>
  `<!-- Generated by agent-service/scripts/render-native-reference.ts. Do not edit; run \`bun run render:native-reference\`. -->\n\n# ${title}\n\n${what}\n\n`;

/** The evidence setting the campaigns run: statistics with samples, full results, flow statistics. */
const EVIDENCE_OPTIONS = { retrievalViews: ["sample_stats", "full"] as const, dataEvidence: true, flowEvidence: true };

export function renderToolDefinitions() {
  const tool = createDataflowTool();
  return [
    {
      name: "dataflow",
      description: String(tool.description),
      schema: asSchema(tool.inputSchema).jsonSchema,
      strict: tool.strict,
    },
  ];
}

export function renderSystemPrompt(): string {
  return (
    HEADER(
      "Native mode: system prompt",
      "The prompt sent with the `dataflow(python, statements)` tool. SYSTEM_PROMPT.txt contains the exact default text; SYSTEM_PROMPT_WITH_EVIDENCE.txt adds data and flow statistics. Definitions persist; every operator invocation has isolated Python state."
    ) +
    "````markdown\n" +
    buildRegisteredNativeSystemPrompt() +
    "\n````\n"
  );
}

export function renderTools(): string {
  return (
    HEADER(
      "Native mode: tool definition",
      "One static dataflow tool with two strings. The model answers by replying without the tool after a result has been shown."
    ) +
    renderToolDefinitions()
      .map(
        tool =>
          `## ${tool.name}\n\n${tool.description}\n\n\`\`\`json\n${JSON.stringify(tool.schema, null, 2)}\n\`\`\`\n\nStrict input: ${tool.strict}. Local validation remains authoritative.\n`
      )
      .join("\n") +
    "\nDefinitions in `python` register before any statement runs, and the call's `set` and `delete` lines apply together or not at all. Then `execute` and `show` lines run in order. After a failed execution, later `show` lines still read the results that completed. A `show result` over several operators reports each one separately.\n\n" +
    "`show operator` reads an operator's statement, inputs and status. `show function` reads registered source, never runtime variables. `show builtin` reads a built-in's full contract. `show schema` pages exact column names and types.\n"
  );
}

export function renderOperators(): string {
  return (
    HEADER(
      "Native mode: operators and edits",
      "Thirteen built-in operators plus public registered Python functions. Positional arguments are graph inputs; settings are keywords. Every operator returns one table."
    ) +
    "## Edit statements\n\nA call has `python` and `statements` strings; an unused string is empty. Both cannot be empty.\n\n```text\nset records: scan(files='data/example.csv')\nset summary: aggregate(records, outputs={'rows': count()})\n```\n\n" +
    "A set replaces the complete definition, inputs, settings, and explicit doc override. Consumers remain connected to its ID. Use `delete id` to remove an existing node. Write each ID once; resolve references against the final acyclic graph. Delete or rewire consumers in the same call as their deleted input. All built-ins accept doc metadata.\n\n" +
    "## Built-in contracts\n\n```text\n" +
    registeredCatalogText(undefined, "full") +
    "\n```\n\n" +
    "## Registered Python\n\nPublic synchronous functions become operator types. A function accepts one DataFrame per ordered input edge and keyword settings, and returns one DataFrame. Zero-input functions load custom data. Imports, helpers, constants, classes, and functions accumulate as ordered definition cells. Each invocation reconstructs its own namespace; execution mutations never become session definitions. Normal Python default binding follows cell order.\n\n" +
    '```python\nimport pandas as pd\n\ndef adjust(table, *, factor=1):\n    """Scale the numeric value column."""\n    return table.assign(value=table[\'value\'] * factor)\n```\n\n```text\nset doubled: adjust(records, factor=2)\n```\n\n' +
    "The receipt confirms function registration or replacement. Replacing a definition conservatively invalidates custom users, measured filters, and their descendants; execution recomputes them. Filter is a built-in measured operator using a registered predicate.\n"
  );
}

export function renderAll(): Record<string, string> {
  return {
    "../docs/native-registered-python-system-prompt.txt": buildRegisteredNativeSystemPrompt(ContextMode.DELTA),
    "SYSTEM_PROMPT.md": renderSystemPrompt(),
    "SYSTEM_PROMPT.txt": buildRegisteredNativeSystemPrompt(ContextMode.DELTA),
    "SYSTEM_PROMPT_WITH_EVIDENCE.txt": buildRegisteredNativeSystemPrompt(ContextMode.DELTA, {
      ...EVIDENCE_OPTIONS,
      retrievalViews: [...EVIDENCE_OPTIONS.retrievalViews],
    }),
    "TOOLS.md": renderTools(),
    "OPERATORS.md": renderOperators(),
  };
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  mkdirSync(root, { recursive: true });
  let stale = 0;
  for (const [name, text] of Object.entries(renderAll())) {
    const path = root + name;
    if (existsSync(path) && readFileSync(path, "utf8") === text) continue;
    stale++;
    if (check) console.error(`stale: native-mode/${name}`);
    else {
      writeFileSync(path, text);
      console.log(`wrote native-mode/${name} (${text.length} chars)`);
    }
  }
  if (check && stale) process.exit(1);
  if (!stale) console.log("native-mode/ is up to date");
}
