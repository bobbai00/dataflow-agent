/** Render the current registered-Python prompt, tool, and operator contracts. */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { asSchema } from "ai";
import { ContextMode } from "../src/types/agent";
import { buildRegisteredNativeSystemPrompt } from "../src/agent/prompts";
import { registeredCatalogText } from "../src/agent/native/registered";
import { createRegisteredDataflowTool } from "../src/agent/tools/dataflow-actions";

const root = fileURLToPath(new URL("../../native-mode/", import.meta.url));
const HEADER = (title: string, what: string) =>
  `<!-- Generated by agent-service/scripts/render-native-reference.ts. Do not edit; run \`bun run render:native-reference\`. -->\n\n# ${title}\n\n${what}\n\n`;

export function renderToolDefinitions() {
  const tool = createRegisteredDataflowTool();
  return [
    {
      name: "dataflow",
      description: String(tool.description),
      schema: asSchema(tool.inputSchema).jsonSchema,
      strict: tool.strict,
    },
  ];
}

export function renderSystemPrompt(): string {
  return (
    HEADER(
      "Native mode: system prompt",
      "The active registered-python-v1 prompt. SYSTEM_PROMPT.txt contains the exact default text. Definitions persist; every operator invocation has isolated Python state. Only execute runs the graph."
    ) +
    "````markdown\n" +
    buildRegisteredNativeSystemPrompt() +
    "\n````\n\n" +
    "The evidence variant adds enabled data/flow guidance. The on-demand variant keeps the same operator contracts and omits the longer repair example. Historical expression-mode prompt builders remain available only for recorded fixtures; they are not sent with the current tool.\n"
  );
}

export function renderTools(): string {
  return (
    HEADER(
      "Native mode: tool definition",
      "One static dataflow tool; registered-python-v1. All examples use the currently exposed schema."
    ) +
    renderToolDefinitions()
      .map(
        tool =>
          `## ${tool.name}\n\n${tool.description}\n\n\`\`\`json\n${JSON.stringify(tool.schema, null, 2)}\n\`\`\`\n\nStrict input: ${tool.strict}. Local validation remains authoritative.\n`
      )
      .join("\n") +
    "\nActions run in order. Each edit stages Python definitions and the final graph atomically. A later error does not undo earlier edits. Only execute computes results. After execution failure, inspect/retrieve may read independent completed results. Batch retrieval reports each target separately. Answer takes content and must be the sole action.\n\n" +
    "Inspect graph/operator reads current definitions and result metadata. Inspect namespace reads registered source and signatures, never runtime variables. Inspect reference reads selected built-in contracts. The current tool does not expose the historical task/state restoration grammar.\n"
  );
}

export function renderOperators(): string {
  return (
    HEADER(
      "Native mode: operators and edits",
      "Twelve built-in operators plus public registered Python functions. Positional arguments are graph inputs; settings are keywords. Every operator returns one table."
    ) +
    "## Edit statements\n\nAn edit has python and changes strings; an unused string is empty. Both cannot be empty.\n\n```text\nset records: scan(files='data/example.csv')\nset summary: aggregate(records, outputs={'rows': count()})\n```\n\n" +
    "A set replaces the complete definition, inputs, settings, and explicit doc override. Consumers remain connected to its ID. Use `delete id` to remove an existing node. Write each ID once; resolve references against the final acyclic graph. Delete or rewire consumers in the same edit as their deleted input. All built-ins accept doc metadata.\n\n" +
    "## Built-in contracts\n\n```text\n" +
    registeredCatalogText(undefined, "full") +
    "\n```\n\n" +
    "## Registered Python\n\nPublic synchronous functions become operator types. A function accepts one DataFrame per ordered input edge and keyword settings, and returns one DataFrame. Zero-input functions load custom data. Imports, helpers, constants, classes, and functions accumulate as ordered definition cells. Each invocation reconstructs its own namespace; execution mutations never become session definitions. Normal Python default binding follows cell order.\n\n" +
    '```python\nimport pandas as pd\n\ndef adjust(table, *, factor=1):\n    """Scale the numeric value column."""\n    return table.assign(value=table[\'value\'] * factor)\n```\n\n```text\nset doubled: adjust(records, factor=2)\n```\n\n' +
    "The edit confirms function registration or replacement. Replacing a definition conservatively invalidates custom users and their descendants; explicit execute recomputes them. Names filter/map/process are retired as model-facing constructors. Historical parser/runtime adapters remain only for old traces.\n"
  );
}

export function renderAll(): Record<string, string> {
  return {
    "../docs/native-registered-python-system-prompt.txt": buildRegisteredNativeSystemPrompt(ContextMode.DELTA),
    "SYSTEM_PROMPT.md": renderSystemPrompt(),
    "SYSTEM_PROMPT.txt": buildRegisteredNativeSystemPrompt(ContextMode.DELTA),
    "SYSTEM_PROMPT_WITH_EVIDENCE.txt": buildRegisteredNativeSystemPrompt(ContextMode.DELTA, {
      retrievalViews: ["full", "sample", "sample_stats"],
      flowEvidence: true,
    }),
    "SYSTEM_PROMPT_TEXT_TURN.txt": buildRegisteredNativeSystemPrompt(ContextMode.DELTA, {
      transport: "text",
      retrievalViews: ["sample_stats", "full"],
      dataEvidence: true,
      flowEvidence: true,
    }),
    "SYSTEM_PROMPT_WITH_STATE.txt": buildRegisteredNativeSystemPrompt(ContextMode.DELTA, {
      stateHistory: true,
      stateLedger: true,
    }),
    "SYSTEM_PROMPT_WITH_HISTORY.txt": buildRegisteredNativeSystemPrompt(ContextMode.DELTA, {
      stateHistory: true,
      retrievalViews: ["sample", "full"],
    }),
    "SYSTEM_PROMPT_ON_DEMAND_WITH_HISTORY.txt": buildRegisteredNativeSystemPrompt(ContextMode.DELTA, {
      nativePromptDetail: "on_demand",
      stateHistory: true,
      retrievalViews: ["sample_stats", "full"],
    }),
    "TOOLS.md": renderTools(),
    "OPERATORS.md": renderOperators(),
  };
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  mkdirSync(root, { recursive: true });
  let stale = 0;
  for (const [name, text] of Object.entries(renderAll())) {
    const path = root + name;
    if (existsSync(path) && readFileSync(path, "utf8") === text) continue;
    stale++;
    if (check) console.error(`stale: native-mode/${name}`);
    else {
      writeFileSync(path, text);
      console.log(`wrote native-mode/${name} (${text.length} chars)`);
    }
  }
  if (check && stale) process.exit(1);
  if (!stale) console.log("native-mode/ is up to date");
}
