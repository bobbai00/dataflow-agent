/**
 * Renders the native-mode reference documents under `<repo>/native-mode/` from
 * the code that produces them, so the documents are what the model receives:
 *
 *   SYSTEM_PROMPT.md  the complete system prompt (default settings: DELTA,
 *                     no optional tools), plus the variant paragraphs
 *   SYSTEM_PROMPT.txt the exact default prompt without documentation wrappers
 *   TOOLS.md          the tool definitions as sent to the provider
 *   OPERATORS.md      the operator reference: grammar, catalog, custom operators
 *
 *   bun run render:native-reference          # write the files
 *   bun run render:native-reference --check  # exit 1 if a file would change
 *
 * `native-reference.test.ts` runs the check, so a prompt, tool or catalog
 * change that is not re-rendered fails the suite.
 */

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { asSchema } from "ai";
import { ContextMode } from "../src/types/agent";
import { buildNativeModeSystemPrompt, nativeEvidenceText } from "../src/agent/prompts";
import { NATIVE_OPERATORS, graphCatalogText, graphOperatorPorts } from "../src/agent/native/catalog";
import { createDataflowTool } from "../src/agent/tools/dataflow-actions";

const root = fileURLToPath(new URL("../../native-mode/", import.meta.url));

/** The JSON Schema the provider receives, whether the tool declared JSON Schema or a Zod schema. */
function schemaOf(tool: any): unknown {
  return asSchema(tool.inputSchema ?? tool.parameters).jsonSchema;
}

export function renderToolDefinitions(): Array<{
  name: string;
  description: string;
  schema: unknown;
  strict?: boolean;
}> {
  const tool = createDataflowTool();
  return [{ name: "dataflow", description: String(tool.description), schema: schemaOf(tool), strict: tool.strict }];
}

const HEADER = (title: string, what: string) =>
  `<!-- Generated by agent-service/scripts/render-native-reference.ts. Do not edit; re-run \`bun run render:native-reference\` in agent-service/. -->\n\n# ${title}\n\n${what}\n\n`;

export function renderSystemPrompt(): string {
  const prompt = buildNativeModeSystemPrompt(ContextMode.DELTA);
  const latest = buildNativeModeSystemPrompt(ContextMode.LATEST);
  const differing = latest.split("\n").filter(line => line.trim() && !prompt.split("\n").includes(line));
  return (
    HEADER(
      "Native mode: system prompt",
      "The complete default prompt, generated from the template and operator catalog. SYSTEM_PROMPT.txt contains just the text sent to the model. Tool definitions are in TOOLS.md."
    ) +
    "````markdown\n" +
    prompt.trim() +
    "\n````\n\n" +
    "## Optional context and evidence settings\n\n" +
    "LATEST context replaces the context paragraph with:\n\n" +
    differing.join("\n") +
    "\n\n" +
    "Enabling evidence adds the matching paragraphs below. The default exposes neither family. " +
    "[SYSTEM_PROMPT_WITH_EVIDENCE.txt](SYSTEM_PROMPT_WITH_EVIDENCE.txt) shows the complete prompt with all three retrieval views and flow evidence enabled, including synthetic retrieval and repair examples.\n\n" +
    nativeEvidenceText({ dataEvidence: true, flowEvidence: true }) +
    "\n"
  );
}

export function renderTools(): string {
  return (
    HEADER(
      "Native mode: tool definition",
      "Native mode exposes one dataflow tool with a brief rationale and an ordered action list. The definition below is generated from the actual tool in agent-service/src/agent/tools/dataflow-actions.ts. Optional recall, resume and compaction tools are off by default."
    ) +
    renderToolDefinitions()
      .map(
        t =>
          `## \`${t.name}\`\n\n${t.description}\n\n\`\`\`json\n${JSON.stringify(t.schema, null, 2)}\n\`\`\`\n\nStrict tool input: \`${t.strict}\`. The SDK sends this flag outside the parameter schema. On configured Claude routes, \`bin/strict_tools.py\` preserves strictness through LiteLLM and moves unsupported constraints and costly regexes into descriptions. Local validation enforces this original schema; graph commands inside \`changes\` are validated by the graph parser.\n`
      )
      .join("\n") +
    "\n## Execution rules\n\n" +
    "The whole request is validated before actions begin. Actions run in order; a failure skips later actions, except that inspect and retrieve may read independent completed results after an execution failure. Completed changes remain. Each Edit is atomic: an invalid command rejects all changes in that Edit.\n\n" +
    "Only execute runs the graph. Retrieve reads existing results for the current graph; editing an operator invalidates its results and those of its downstream consumers. Each retrieved table is frozen at the point of retrieval.\n\n" +
    "Inspection returns definitions, named ports, explicit edges and optional Python implementations. Deleting an operator removes its incident edges and reports them. Edges change only through deletion and creation.\n\n" +
    "Answer must be the only action and ends the model loop. Actions that depend on a returned observation belong in the next call.\n"
  );
}

export function renderOperators(): string {
  const rows = NATIVE_OPERATORS.map(def => `| \`${def.name}\` | ${graphOperatorPorts(def)} | ${def.brief} |`);
  return (
    HEADER(
      "Native mode: operators and ports",
      "Generated from the operator catalog. Every operator produces one output table on out; edges provide its input tables."
    ) +
    `
## Graph commands

\`dataflow(reasoning, actions)\` exposes five actions: Inspect, Edit, Execute, Retrieve and Answer. An Edit's \`changes\` string contains these commands:

\`\`\`text
create operator <id>: <operator>(parameters)
update operator <id>: <operator>(parameters)
delete operator <id>
create edge <source>.out -> <target>.<input_port>
delete edge <source>.out -> <target>.<input_port>
\`\`\`

Create requires a new identifier. Update replaces the definition and preserves its identifier and every connection. Delete removes the operator and all incident edges, which are listed in the observation. Edges cannot be updated; delete and recreate them. Each Edit is atomic. Unconnected operators may exist during construction; Execute requires complete inputs and an acyclic graph.

## Catalog (${NATIVE_OPERATORS.length} operators)

| Operator | Ports | Meaning |
|---|---|---|
${rows.join("\n")}

## Parameters and contracts

Operator expressions contain parameters only. No upstream table identifiers appear inside the expression. Defaults are shown. Data types are bare names; reducers and window functions name columns.

\`\`\`text
${graphCatalogText()}
\`\`\`

## Python implementations

Keep loading, deriving columns, filtering, joining and aggregation in separate predefined operators. Use process for one operation the catalog cannot express. A custom calculation consumes connected tables; a source process loads an unsupported format and returns a parsed table for downstream operators. Build a known chain and its edges in one Edit.

Filter and map accept lambdas or functions. A filter receives a row and returns a boolean; a map receives a row and returns the complete output row. Process receives one DataFrame per indexed input port and returns a DataFrame. Its function parameter count declares its input ports; a zero-parameter function is a loader. Every callback operator requires doc, describing the output's meaning.

Indent complete function definitions under the operator that uses them. Helpers belong in the same block, and imports belong inside functions. Definitions do not carry across operators or updates.

\`\`\`dataflow
create operator correlation: process(fn=correlate, doc="Pearson correlation between yearly changes")
    def correlate(df):
        import pandas as pd
        return pd.DataFrame({"correlation": [df["x"].corr(df["y"])]})
create edge measurements.out -> correlation.in[0]
\`\`\`

## Execution and caching

The editor stages and validates commands before committing. The graph's ordered port connections become the native operator's inputs, its revision and generated engine code. Edge changes invalidate the receiver and its descendants. Valid results on independent branches remain available. Retrieve never executes and observations preserve the result version originally returned.

Historical assignment-based traces remain replayable through their original edit interpreter. Newly generated calls use graph commands.
`
  );
}

export function renderAll(): Record<string, string> {
  return {
    "SYSTEM_PROMPT.md": renderSystemPrompt(),
    "SYSTEM_PROMPT.txt": buildNativeModeSystemPrompt(ContextMode.DELTA),
    "SYSTEM_PROMPT_WITH_EVIDENCE.txt": buildNativeModeSystemPrompt(ContextMode.DELTA, {
      retrievalViews: ["full", "sample", "sample_stats"],
      flowEvidence: true,
    }),
    "TOOLS.md": renderTools(),
    "OPERATORS.md": renderOperators(),
  };
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  mkdirSync(root, { recursive: true });
  let stale = 0;
  for (const [name, text] of Object.entries(renderAll())) {
    const path = root + name;
    const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
    if (current === text) continue;
    stale++;
    if (check) console.error(`stale: native-mode/${name}`);
    else {
      writeFileSync(path, text);
      console.log(`wrote native-mode/${name} (${text.length} chars)`);
    }
  }
  if (check && stale) process.exit(1);
  if (!stale) console.log("native-mode/ is up to date");
}
