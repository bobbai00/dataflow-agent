/**
 * Renders the native-mode reference documents under `<repo>/native-mode/` from
 * the code that produces them, so the documents are what the model receives:
 *
 *   SYSTEM_PROMPT.md  the complete system prompt (default settings: DELTA,
 *                     no optional tools), plus the variant paragraphs
 *   TOOLS.md          the tool definitions as sent to the provider
 *   OPERATORS.md      the operator reference: grammar, catalog, custom operators
 *
 *   bun run render:native-reference          # write the files
 *   bun run render:native-reference --check  # exit 1 if a file would change
 *
 * `native-reference.test.ts` runs the check, so a prompt, tool or catalog
 * change that is not re-rendered fails the suite.
 */

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { asSchema } from "ai";
import { ContextMode } from "../src/types/agent";
import { buildNativeModeSystemPrompt } from "../src/agent/prompts";
import { NATIVE_OPERATORS, nativeCatalogText } from "../src/agent/native/catalog";
import { nativeTestTools } from "../src/agent/native/test-support";

const root = fileURLToPath(new URL("../../native-mode/", import.meta.url));

/** The JSON Schema the provider receives, whether the tool declared JSON Schema or a Zod schema. */
function schemaOf(tool: any): unknown {
  return asSchema(tool.inputSchema ?? tool.parameters).jsonSchema;
}

export function renderToolDefinitions(): Array<{ name: string; description: string; schema: unknown }> {
  const { tools } = nativeTestTools();
  const all: Record<string, any> = { ...tools };
  return ["dataflow"].map(name => ({
    name,
    description: String(all[name].description),
    schema: schemaOf(all[name]),
  }));
}

const HEADER = (title: string, what: string) =>
  `<!-- Generated by agent-service/scripts/render-native-reference.ts. Do not edit; re-run \`bun run render:native-reference\` in agent-service/. -->\n\n# ${title}\n\n${what}\n\n`;

export function renderSystemPrompt(): string {
  const prompt = buildNativeModeSystemPrompt(ContextMode.DELTA);
  const latest = buildNativeModeSystemPrompt(ContextMode.LATEST);
  const variants: Array<[string, string]> = [];
  const base = prompt.split("\n");
  const other = latest.split("\n");
  // Paragraphs that differ between the two default layouts are the layout-dependent ones.
  const differing = other.filter(line => line.trim() && !base.includes(line));
  return (
    HEADER(
      "Native mode: the complete system prompt",
      "This is the system prompt an agent created with the default settings receives (`agentMode: native`, `contextMode: delta`, no optional tools). The operator reference inside it is generated from the catalog in `agent-service/src/agent/native/catalog.ts`; the rest is `agent-service/src/agent/prompts/native-mode.md` with its placeholders filled by `buildNativeModeSystemPrompt` in `agent-service/src/agent/prompts.ts`. Tool descriptions are not part of this text; they travel as tool definitions (see TOOLS.md)."
    ) +
    "## Prompt (contextMode = delta, messageLayout = native)\n\n" +
    "````markdown\n" +
    prompt.trim() +
    "\n````\n\n" +
    "## Layout-dependent paragraphs\n\n" +
    "`contextMode: latest` (one snapshot of the current dataflow instead of the event transcript) replaces the context-layout, observation-scope and inspection-location paragraphs with:\n\n" +
    differing.map(line => "> " + line).join("\n>\n") +
    "\n\n" +
    "Enabling `enableRecallTool` appends one sentence describing `recallState`; `versionedMode` and `sessionTurns` swap in the multi-turn catalog / session paragraphs. Every variant is produced by the same builder.\n" +
    variants.map(([k, v]) => `\n### ${k}\n\n${v}\n`).join("")
  );
}

export function renderTools(): string {
  const tools = renderToolDefinitions();
  return (
    HEADER(
      "Native mode: tool definitions",
      "Native mode exposes one tool, `dataflow`, whose three arguments create or modify operators (`edits`), remove them (`delete`) and choose which tables to see (`observe`). The definition below is exactly what is sent to the provider (name, description, JSON Schema of the input). Every operator is written inside `edits`; there is no tool per operator. Optional tools (`recallState`, `resumeFrom`, `compactContext`) are off by default and not listed here. Source: `agent-service/src/agent/tools/native-batch-tools.ts`, `native-upsert.ts`."
    ) +
    tools
      .map(
        t =>
          `## \`${t.name}\`\n\n**Description sent to the model**\n\n> ${t.description.replace(/\n/g, "\n> ")}\n\n**Input schema**\n\n\`\`\`json\n${JSON.stringify(t.schema, null, 2)}\n\`\`\`\n`
      )
      .join("\n") +
    "\n## How a call is processed\n\n" +
    "1. `delete` removes the listed operators first (refused while another surviving operator reads one). `edits` is parsed with Python's `ast` (`agent-service/src/agent/native/python/program_parser.py`). A statement that does not parse is reported at its line as `PROGRAM_SYNTAX` and skipped; its dependents are blocked and the other statements land.\n" +
    "2. Each `name = operator(...)` statement is normalized against the catalog (`catalog.ts`): positional arguments become the operator's input tables, keywords its parameters; unknown keywords, bad enums, wrong types, undefined functions and nested operator calls are `INVALID_ARGUMENTS` for that statement only.\n" +
    "3. The Python runtime validates every statement without data (argument rules, function syntax and signatures), then the scheduler lands statements in dependency order as `DataLoading` / `DataProcessing` engine operators. A rejected statement blocks its dependents (`UPSTREAM_FAILED`); independent statements still land.\n" +
    "4. The workflow executes once. Tables named in `observe` are rendered (shape, schema, sample rows, evidence when enabled); other successes show a receipt; failures are always shown with `[CODE; stage; revision] message`, `Hint:`, `Field:` and the failing source line.\n"
  );
}

export function renderOperators(): string {
  const rows = NATIVE_OPERATORS.map(
    d =>
      `| \`${d.name}\` | ${d.type} | ${d.inputs === "many" ? "1 or more (0 for a `process` loader)" : d.inputs} | ${d.rowEffect} | \`${d.signature}\` |`
  );
  return (
    HEADER(
      "Native mode: tools and operators",
      "What the agent can call, what an operator is, and how a statement becomes an engine operator. The catalog table and the operator reference are generated from `agent-service/src/agent/native/catalog.ts`."
    ) +
    `## Tools versus operators

The model sees one **tool**: \`dataflow(edits, delete, observe)\` (TOOLS.md). Operators are not tools. Every operator is one statement inside \`edits\`:

\`\`\`python
id = operator(input_id, ..., parameter=value, ...)
\`\`\`

- The left-hand **id** names the operator and its output table. Assigning to an existing name revises that operator in place and keeps its consumers. Names are Python identifiers that are not Python keywords and not operator names; each name is assigned once per program.
- **Positional arguments** are the ids of other operators, whose output tables are the inputs. The DAG edges are derived from them; there is no separate edge list.
- **Keyword arguments** are the operator's parameters. Types are bare names (\`str\`, \`int64\`, \`float64\`, \`bool\`, \`datetime\`); reducers and window functions are calls (\`mean("x")\`, \`count()\`, \`lag("x", 1)\`).
- **No nesting.** \`limit(sort(t, by=["x"]), 1)\` is refused; every intermediate table gets its own statement so it can be observed, revised and reported on.
- **Functions** are lambdas or \`def\`s written in the same \`edits\` and passed by name. Only \`filter\`, \`map\` and \`process\` take them; the function's return type is the contract (bool, dict, DataFrame).
- A program may hold many statements, in any order; the scheduler orders them by their inputs. A statement may reference tables from earlier calls.

## The catalog (${NATIVE_OPERATORS.length} operators)

| Operator | Engine type | Inputs | Row effect | Signature |
|---|---|---|---|---|
${rows.join("\n")}

Row effect is the contract the runtime enforces and flow evidence reports: \`none\` keeps every row in place, \`drop\` only removes rows, \`unknown\` promises nothing.

## Operator reference (as it appears in the system prompt)

\`T\` stands for an input table; defaults are shown.

\`\`\`text
${nativeCatalogText()}
\`\`\`

## The three custom operators

| Operator | Function shape | Contract |
|---|---|---|
| \`filter(T, fn)\` | \`fn(row) -> bool\` | drop-only: True keeps the row, False or None drops it |
| \`map(T, fn)\` | \`fn(row) -> dict\` (the new row) | row-preserving: one dict per row, same keys in every row, column types inferred from the values; \`{**row, ...}\` keeps the input columns |
| \`process(T1, ..., Tn, fn=f, doc="...")\` | \`f(df1, ..., dfn) -> DataFrame\`; \`f()\` with no inputs is a loader | unknown: any rows, unique string column names, scalar cells, UTC datetimes; \`doc\` is the one sentence shown with its results |

\`row\` is a read-only mapping of the input columns; a missing value is None. The columns a function actually reads are measured at run time (\`predicateColumns\` for filter, \`readColumns\` and \`columnDependencies\` for map, where \`{**row}\` copies are not counted as reads) and drive the flow evidence and lineage, so nothing about the columns is declared.

## What an operator looks like end to end

Program statement:

\`\`\`python
positive = filter(typed, lambda row: row["value"] is not None and row["value"] > 0)
\`\`\`

Normalized view stored on the operator (\`nativeOp\`):

\`\`\`json
{ "type": "Filter", "inputs": ["typed"],
  "properties": { "func": "def apply(row):\\n    return row[\\"value\\"] is not None and row[\\"value\\"] > 0", "entry": "apply" },
  "revision": "<hash of type + inputs + properties>" }
\`\`\`

Engine operator: one \`DataProcessing\` (or \`DataLoading\` for a source) whose code hands this JSON to the shared Python runtime (\`agent-service/src/agent/native/python/runtime.py\`), which validates the contract, runs it with pandas and records the counters that flow evidence reports (\`Filter kept=135/1388\`). The model never sees that code; it sees the statement it wrote.

## Errors

Every failure is one receipt line per operator: \`[CODE; stage; revision] message\`, then \`Hint:\`, \`Field:\` (the offending argument) and, for custom code, the failing line. \`PROGRAM_SYNTAX\` fails the statement that does not parse; \`INVALID_ARGUMENTS\` fails one statement; runtime codes (\`MISSING_COLUMN\`, \`CAST_INVALID_VALUE\`, \`JOIN_CARDINALITY\`, \`UNION_TYPE\`, ...) name the column, value or option; a consumer of a failed operator is told its upstream failed, a bystander that the run stopped elsewhere. The full taxonomy is in \`docs/native-expression-mode.md\` and \`agent-service/benchmark/tests/test_native_error_taxonomy.py\`.
`
  );
}

export function renderAll(): Record<string, string> {
  return {
    "SYSTEM_PROMPT.md": renderSystemPrompt(),
    "TOOLS.md": renderTools(),
    "OPERATORS.md": renderOperators(),
  };
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  mkdirSync(root, { recursive: true });
  let stale = 0;
  for (const [name, text] of Object.entries(renderAll())) {
    const path = root + name;
    const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
    if (current === text) continue;
    stale++;
    if (check) console.error(`stale: native-mode/${name}`);
    else {
      writeFileSync(path, text);
      console.log(`wrote native-mode/${name} (${text.length} chars)`);
    }
  }
  if (check && stale) process.exit(1);
  if (!stale) console.log("native-mode/ is up to date");
}
